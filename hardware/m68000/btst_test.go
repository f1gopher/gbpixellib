package m68000

import "testing"

func TestDisassembleBTST(t *testing.T) {
	testCases := []struct {
		bytes    []uint8
		expected string
	}{
		// BTST - Bit Test
		// Format 1: BTST Dn,<ea> (dynamic bit number from register)
		// Format: 0000 rrr 100 eee mmm (where rrr is the register number)

		// Format 2: BTST #<data>,<ea> (static bit number from immediate)
		// Format: 0000 1000 00 eee mmm (followed by bit number as immediate word)

		// BTST Dn,Dm (dynamic bit number, data register destination)
		{[]uint8{0x01, 0x00}, "BTST D0,D0"},
		{[]uint8{0x03, 0x01}, "BTST D1,D1"},
		{[]uint8{0x05, 0x02}, "BTST D2,D2"},
		{[]uint8{0x07, 0x03}, "BTST D3,D3"},
		{[]uint8{0x09, 0x04}, "BTST D4,D4"},
		{[]uint8{0x0B, 0x05}, "BTST D5,D5"},
		{[]uint8{0x0D, 0x06}, "BTST D6,D6"},
		{[]uint8{0x0F, 0x07}, "BTST D7,D7"},
		{[]uint8{0x01, 0x07}, "BTST D0,D7"},
		{[]uint8{0x03, 0x06}, "BTST D1,D6"},
		{[]uint8{0x05, 0x05}, "BTST D2,D5"},
		{[]uint8{0x07, 0x04}, "BTST D3,D4"},
		{[]uint8{0x09, 0x03}, "BTST D4,D3"},
		{[]uint8{0x0B, 0x02}, "BTST D5,D2"},
		{[]uint8{0x0D, 0x01}, "BTST D6,D1"},
		{[]uint8{0x0F, 0x00}, "BTST D7,D0"},

		// BTST Dn,(Am) (dynamic bit number, memory destination)
		{[]uint8{0x01, 0x10}, "BTST D0,(A0)"},
		{[]uint8{0x03, 0x11}, "BTST D1,(A1)"},
		{[]uint8{0x05, 0x12}, "BTST D2,(A2)"},
		{[]uint8{0x07, 0x13}, "BTST D3,(A3)"},
		{[]uint8{0x09, 0x14}, "BTST D4,(A4)"},
		{[]uint8{0x0B, 0x15}, "BTST D5,(A5)"},
		{[]uint8{0x0D, 0x16}, "BTST D6,(A6)"},
		{[]uint8{0x0F, 0x17}, "BTST D7,(A7)"},

		// BTST Dn,(Am)+ (dynamic bit number, memory destination with postincrement)
		{[]uint8{0x01, 0x18}, "BTST D0,(A0)+"},
		{[]uint8{0x03, 0x19}, "BTST D1,(A1)+"},
		{[]uint8{0x05, 0x1A}, "BTST D2,(A2)+"},
		{[]uint8{0x07, 0x1B}, "BTST D3,(A3)+"},
		{[]uint8{0x09, 0x1C}, "BTST D4,(A4)+"},
		{[]uint8{0x0B, 0x1D}, "BTST D5,(A5)+"},
		{[]uint8{0x0D, 0x1E}, "BTST D6,(A6)+"},
		{[]uint8{0x0F, 0x1F}, "BTST D7,(A7)+"},

		// BTST Dn,-(Am) (dynamic bit number, memory destination with predecrement)
		{[]uint8{0x01, 0x20}, "BTST D0,-(A0)"},
		{[]uint8{0x03, 0x21}, "BTST D1,-(A1)"},
		{[]uint8{0x05, 0x22}, "BTST D2,-(A2)"},
		{[]uint8{0x07, 0x23}, "BTST D3,-(A3)"},
		{[]uint8{0x09, 0x24}, "BTST D4,-(A4)"},
		{[]uint8{0x0B, 0x25}, "BTST D5,-(A5)"},
		{[]uint8{0x0D, 0x26}, "BTST D6,-(A6)"},
		{[]uint8{0x0F, 0x27}, "BTST D7,-(A7)"},

		// BTST Dn,d16(Am) (dynamic bit number, memory destination with displacement)
		{[]uint8{0x01, 0x28, 0x12, 0x34}, "BTST D0,(0x1234,A0)"},
		{[]uint8{0x03, 0x29, 0x56, 0x78}, "BTST D1,(0x5678,A1)"},
		{[]uint8{0x05, 0x2A, 0x9A, 0xBC}, "BTST D2,(0x9ABC,A2)"},
		{[]uint8{0x07, 0x2B, 0xDE, 0xF0}, "BTST D3,(0xDEF0,A3)"},
		{[]uint8{0x09, 0x2C, 0x11, 0x22}, "BTST D4,(0x1122,A4)"},
		{[]uint8{0x0B, 0x2D, 0x33, 0x44}, "BTST D5,(0x3344,A5)"},
		{[]uint8{0x0D, 0x2E, 0x55, 0x66}, "BTST D6,(0x5566,A6)"},
		{[]uint8{0x0F, 0x2F, 0x77, 0x88}, "BTST D7,(0x7788,A7)"},

		// BTST Dn,d8(Am,Xn) (dynamic bit number, memory destination with index)
		{[]uint8{0x01, 0x30, 0x12, 0x34}, "BTST D0,(0x12,A0,D4.W)"},
		{[]uint8{0x03, 0x31, 0x56, 0x78}, "BTST D1,(0x56,A1,D7.W)"},
		{[]uint8{0x05, 0x32, 0x9A, 0xB0}, "BTST D2,(0x9A,A2,D0.W)"},
		{[]uint8{0x07, 0x33, 0xDE, 0xF3}, "BTST D3,(0xDE,A3,D3.W)"},
		{[]uint8{0x01, 0x30, 0x12, 0xB4}, "BTST D0,(0x12,A0,A4.W)"},
		{[]uint8{0x03, 0x31, 0x56, 0xF7}, "BTST D1,(0x56,A1,A7.W)"},

		// BTST Dn,xxx.W (dynamic bit number, absolute short address)
		{[]uint8{0x01, 0x38, 0x12, 0x34}, "BTST D0,(0x1234).W"},
		{[]uint8{0x03, 0x38, 0x56, 0x78}, "BTST D1,(0x5678).W"},
		{[]uint8{0x05, 0x38, 0x9A, 0xBC}, "BTST D2,(0x9ABC).W"},

		// BTST Dn,xxx.L (dynamic bit number, absolute long address)
		{[]uint8{0x01, 0x39, 0x12, 0x34, 0x56, 0x78}, "BTST D0,(0x12345678).L"},
		{[]uint8{0x03, 0x39, 0x9A, 0xBC, 0xDE, 0xF0}, "BTST D1,(0x9ABCDEF0).L"},

		// BTST Dn,PC-relative with displacement
		{[]uint8{0x01, 0x3A, 0x12, 0x34}, "BTST D0,(0x1234,PC)"},
		{[]uint8{0x03, 0x3A, 0x56, 0x78}, "BTST D1,(0x5678,PC)"},

		// BTST Dn,PC-relative with index
		{[]uint8{0x01, 0x3B, 0x12, 0x34}, "BTST D0,(0x12,PC,D4.W)"},
		{[]uint8{0x03, 0x3B, 0x56, 0x78}, "BTST D1,(0x56,PC,D7.W)"},
		{[]uint8{0x01, 0x3B, 0x12, 0xB4}, "BTST D0,(0x12,PC,A4.W)"},

		// BTST Dn,#<data> - immediate data as source (special case)
		{[]uint8{0x01, 0x3C, 0x12, 0x34}, "BTST D0,#0x1234"},
		{[]uint8{0x03, 0x3C, 0xAB, 0xCD}, "BTST D1,#0xABCD"},

		// BTST #imm,Dn (static bit number, data register destination)
		{[]uint8{0x08, 0x00, 0x00, 0x00}, "BTST #0,D0"},
		{[]uint8{0x08, 0x01, 0x00, 0x07}, "BTST #7,D1"},
		{[]uint8{0x08, 0x02, 0x00, 0x0F}, "BTST #15,D2"},
		{[]uint8{0x08, 0x03, 0x00, 0x1F}, "BTST #31,D3"},  // Maximum bit number for long word
		{[]uint8{0x08, 0x04, 0x00, 0x20}, "BTST #32,D4"},  // Will be modulo 32
		{[]uint8{0x08, 0x05, 0x00, 0xFF}, "BTST #255,D5"}, // Will be modulo 32

		// BTST #imm,(Am) (static bit number, memory destination)
		{[]uint8{0x08, 0x10, 0x00, 0x00}, "BTST #0,(A0)"},
		{[]uint8{0x08, 0x11, 0x00, 0x07}, "BTST #7,(A1)"},
		{[]uint8{0x08, 0x12, 0x00, 0x08}, "BTST #8,(A2)"},   // Will be modulo 8 for memory ops
		{[]uint8{0x08, 0x13, 0x00, 0xFF}, "BTST #255,(A3)"}, // Will be modulo 8 for memory ops

		// BTST #imm,(Am)+ (static bit number, memory destination with postincrement)
		{[]uint8{0x08, 0x18, 0x00, 0x00}, "BTST #0,(A0)+"},
		{[]uint8{0x08, 0x19, 0x00, 0x07}, "BTST #7,(A1)+"},

		// BTST #imm,-(Am) (static bit number, memory destination with predecrement)
		{[]uint8{0x08, 0x20, 0x00, 0x00}, "BTST #0,-(A0)"},
		{[]uint8{0x08, 0x21, 0x00, 0x07}, "BTST #7,-(A1)"},

		// BTST #imm,d16(Am) (static bit number, memory destination with displacement)
		{[]uint8{0x08, 0x28, 0x12, 0x34, 0x00, 0x00}, "BTST #0,(0x1234,A0)"},
		{[]uint8{0x08, 0x29, 0x56, 0x78, 0x00, 0x07}, "BTST #7,(0x5678,A1)"},

		// BTST #imm,d8(Am,Xn) (static bit number, memory destination with index)
		{[]uint8{0x08, 0x30, 0x12, 0x34, 0x00, 0x00}, "BTST #0,(0x12,A0,D4.W)"},
		{[]uint8{0x08, 0x31, 0x56, 0x78, 0x00, 0x07}, "BTST #7,(0x56,A1,D7.W)"},
		{[]uint8{0x08, 0x30, 0x12, 0xB4, 0x00, 0x00}, "BTST #0,(0x12,A0,A4.W)"},

		// BTST #imm,xxx.W (static bit number, absolute short address)
		{[]uint8{0x08, 0x38, 0x12, 0x34, 0x00, 0x00}, "BTST #0,(0x1234).W"},
		{[]uint8{0x08, 0x38, 0x56, 0x78, 0x00, 0x07}, "BTST #7,(0x5678).W"},

		// BTST #imm,xxx.L (static bit number, absolute long address)
		{[]uint8{0x08, 0x39, 0x12, 0x34, 0x56, 0x78, 0x00, 0x00}, "BTST #0,(0x12345678).L"},
		{[]uint8{0x08, 0x39, 0x9A, 0xBC, 0xDE, 0xF0, 0x00, 0x07}, "BTST #7,(0x9ABCDEF0).L"},

		// BTST #imm,PC-relative with displacement
		{[]uint8{0x08, 0x3A, 0x12, 0x34, 0x00, 0x00}, "BTST #0,(0x1234,PC)"},
		{[]uint8{0x08, 0x3A, 0x56, 0x78, 0x00, 0x07}, "BTST #7,(0x5678,PC)"},

		// BTST #imm,PC-relative with index
		{[]uint8{0x08, 0x3B, 0x12, 0x34, 0x00, 0x00}, "BTST #0,(0x12,PC,D4.W)"},
		{[]uint8{0x08, 0x3B, 0x56, 0x78, 0x00, 0x07}, "BTST #7,(0x56,PC,D7.W)"},
		{[]uint8{0x08, 0x3B, 0x12, 0xB4, 0x00, 0x00}, "BTST #0,(0x12,PC,A4.W)"},

		// BTST #imm,#<data> - immediate data as source (special case)
		{[]uint8{0x08, 0x3C, 0x12, 0x34, 0x00, 0x00}, "BTST #0,#0x1234"},
		{[]uint8{0x08, 0x3C, 0xAB, 0xCD, 0x00, 0x07}, "BTST #7,#0xABCD"},
	}

	for _, tc := range testCases {
		t.Run(tc.expected, func(t *testing.T) {
			result := DisassembleInstruction(tc.bytes, 0)
			if result != tc.expected {
				t.Errorf("Expected %s, got %s", tc.expected, result)
			}
		})
	}
}
