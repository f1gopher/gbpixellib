package m68000

import "testing"

func TestDisassembleCMPI(t *testing.T) {
	testCases := []struct {
		bytes    []uint8
		expected string
	}{
		// CMPI - Compare Immediate
		// Format: 0000 1100 ss eeeeee
		// Where:
		// - ss is the size (00=byte, 01=word, 10=long)
		// - eeeeee defines the effective address (destination operand)
		// Followed by immediate data (byte, word, or long)

		// CMPI.B #imm,Dn (Compare immediate byte to data register)
		{[]uint8{0x0C, 0x00, 0x00, 0x01}, "CMPI.B #0x01,D0"},
		{[]uint8{0x0C, 0x01, 0x00, 0x7F}, "CMPI.B #0x7F,D1"},
		{[]uint8{0x0C, 0x02, 0x00, 0x80}, "CMPI.B #0x80,D2"},
		{[]uint8{0x0C, 0x03, 0x00, 0xFF}, "CMPI.B #0xFF,D3"},
		{[]uint8{0x0C, 0x04, 0x00, 0x42}, "CMPI.B #0x42,D4"},
		{[]uint8{0x0C, 0x05, 0x00, 0xA5}, "CMPI.B #0xA5,D5"},
		{[]uint8{0x0C, 0x06, 0x00, 0x55}, "CMPI.B #0x55,D6"},
		{[]uint8{0x0C, 0x07, 0x00, 0xAA}, "CMPI.B #0xAA,D7"},

		// CMPI.W #imm,Dn (Compare immediate word to data register)
		{[]uint8{0x0C, 0x40, 0x00, 0x01}, "CMPI.W #0x0001,D0"},
		{[]uint8{0x0C, 0x41, 0x7F, 0xFF}, "CMPI.W #0x7FFF,D1"},
		{[]uint8{0x0C, 0x42, 0x80, 0x00}, "CMPI.W #0x8000,D2"},
		{[]uint8{0x0C, 0x43, 0xFF, 0xFF}, "CMPI.W #0xFFFF,D3"},
		{[]uint8{0x0C, 0x44, 0x12, 0x34}, "CMPI.W #0x1234,D4"},
		{[]uint8{0x0C, 0x45, 0x56, 0x78}, "CMPI.W #0x5678,D5"},
		{[]uint8{0x0C, 0x46, 0x9A, 0xBC}, "CMPI.W #0x9ABC,D6"},
		{[]uint8{0x0C, 0x47, 0xDE, 0xF0}, "CMPI.W #0xDEF0,D7"},

		// CMPI.L #imm,Dn (Compare immediate long to data register)
		{[]uint8{0x0C, 0x80, 0x00, 0x00, 0x00, 0x01}, "CMPI.L #0x00000001,D0"},
		{[]uint8{0x0C, 0x81, 0x7F, 0xFF, 0xFF, 0xFF}, "CMPI.L #0x7FFFFFFF,D1"},
		{[]uint8{0x0C, 0x82, 0x80, 0x00, 0x00, 0x00}, "CMPI.L #0x80000000,D2"},
		{[]uint8{0x0C, 0x83, 0xFF, 0xFF, 0xFF, 0xFF}, "CMPI.L #0xFFFFFFFF,D3"},
		{[]uint8{0x0C, 0x84, 0x12, 0x34, 0x56, 0x78}, "CMPI.L #0x12345678,D4"},
		{[]uint8{0x0C, 0x85, 0x9A, 0xBC, 0xDE, 0xF0}, "CMPI.L #0x9ABCDEF0,D5"},
		{[]uint8{0x0C, 0x86, 0x01, 0x23, 0x45, 0x67}, "CMPI.L #0x01234567,D6"},
		{[]uint8{0x0C, 0x87, 0x89, 0xAB, 0xCD, 0xEF}, "CMPI.L #0x89ABCDEF,D7"},

		// CMPI.B #imm,(An) (Compare immediate byte to memory)
		{[]uint8{0x0C, 0x10, 0x00, 0x01}, "CMPI.B #0x01,(A0)"},
		{[]uint8{0x0C, 0x11, 0x00, 0x7F}, "CMPI.B #0x7F,(A1)"},
		{[]uint8{0x0C, 0x12, 0x00, 0x80}, "CMPI.B #0x80,(A2)"},
		{[]uint8{0x0C, 0x13, 0x00, 0xFF}, "CMPI.B #0xFF,(A3)"},
		{[]uint8{0x0C, 0x14, 0x00, 0x42}, "CMPI.B #0x42,(A4)"},
		{[]uint8{0x0C, 0x15, 0x00, 0xA5}, "CMPI.B #0xA5,(A5)"},
		{[]uint8{0x0C, 0x16, 0x00, 0x55}, "CMPI.B #0x55,(A6)"},
		{[]uint8{0x0C, 0x17, 0x00, 0xAA}, "CMPI.B #0xAA,(A7)"},

		// CMPI.W #imm,(An) (Compare immediate word to memory)
		{[]uint8{0x0C, 0x50, 0x00, 0x01}, "CMPI.W #0x0001,(A0)"},
		{[]uint8{0x0C, 0x51, 0x7F, 0xFF}, "CMPI.W #0x7FFF,(A1)"},
		{[]uint8{0x0C, 0x52, 0x80, 0x00}, "CMPI.W #0x8000,(A2)"},
		{[]uint8{0x0C, 0x53, 0xFF, 0xFF}, "CMPI.W #0xFFFF,(A3)"},

		// CMPI.L #imm,(An) (Compare immediate long to memory)
		{[]uint8{0x0C, 0x90, 0x00, 0x00, 0x00, 0x01}, "CMPI.L #0x00000001,(A0)"},
		{[]uint8{0x0C, 0x91, 0x7F, 0xFF, 0xFF, 0xFF}, "CMPI.L #0x7FFFFFFF,(A1)"},
		{[]uint8{0x0C, 0x92, 0x80, 0x00, 0x00, 0x00}, "CMPI.L #0x80000000,(A2)"},
		{[]uint8{0x0C, 0x93, 0xFF, 0xFF, 0xFF, 0xFF}, "CMPI.L #0xFFFFFFFF,(A3)"},

		// CMPI.B #imm,(An)+ (Compare immediate byte to memory with postincrement)
		{[]uint8{0x0C, 0x18, 0x00, 0x01}, "CMPI.B #0x01,(A0)+"},
		{[]uint8{0x0C, 0x19, 0x00, 0x7F}, "CMPI.B #0x7F,(A1)+"},
		{[]uint8{0x0C, 0x1A, 0x00, 0x80}, "CMPI.B #0x80,(A2)+"},
		{[]uint8{0x0C, 0x1B, 0x00, 0xFF}, "CMPI.B #0xFF,(A3)+"},

		// CMPI.W #imm,(An)+ (Compare immediate word to memory with postincrement)
		{[]uint8{0x0C, 0x58, 0x00, 0x01}, "CMPI.W #0x0001,(A0)+"},
		{[]uint8{0x0C, 0x59, 0x7F, 0xFF}, "CMPI.W #0x7FFF,(A1)+"},

		// CMPI.L #imm,(An)+ (Compare immediate long to memory with postincrement)
		{[]uint8{0x0C, 0x98, 0x00, 0x00, 0x00, 0x01}, "CMPI.L #0x00000001,(A0)+"},
		{[]uint8{0x0C, 0x99, 0x7F, 0xFF, 0xFF, 0xFF}, "CMPI.L #0x7FFFFFFF,(A1)+"},

		// CMPI.B #imm,-(An) (Compare immediate byte to memory with predecrement)
		{[]uint8{0x0C, 0x20, 0x00, 0x01}, "CMPI.B #0x01,-(A0)"},
		{[]uint8{0x0C, 0x21, 0x00, 0x7F}, "CMPI.B #0x7F,-(A1)"},
		{[]uint8{0x0C, 0x22, 0x00, 0x80}, "CMPI.B #0x80,-(A2)"},
		{[]uint8{0x0C, 0x23, 0x00, 0xFF}, "CMPI.B #0xFF,-(A3)"},

		// CMPI.W #imm,-(An) (Compare immediate word to memory with predecrement)
		{[]uint8{0x0C, 0x60, 0x00, 0x01}, "CMPI.W #0x0001,-(A0)"},
		{[]uint8{0x0C, 0x61, 0x7F, 0xFF}, "CMPI.W #0x7FFF,-(A1)"},

		// CMPI.L #imm,-(An) (Compare immediate long to memory with predecrement)
		{[]uint8{0x0C, 0xA0, 0x00, 0x00, 0x00, 0x01}, "CMPI.L #0x00000001,-(A0)"},
		{[]uint8{0x0C, 0xA1, 0x7F, 0xFF, 0xFF, 0xFF}, "CMPI.L #0x7FFFFFFF,-(A1)"},

		// CMPI.B #imm,d16(An) (Compare immediate byte to memory with displacement)
		{[]uint8{0x0C, 0x28, 0x00, 0x01, 0x12, 0x34}, "CMPI.B #0x01,(0x1234,A0)"},
		{[]uint8{0x0C, 0x29, 0x00, 0x7F, 0x56, 0x78}, "CMPI.B #0x7F,(0x5678,A1)"},
		{[]uint8{0x0C, 0x2A, 0x00, 0x80, 0x9A, 0xBC}, "CMPI.B #0x80,(0x9ABC,A2)"},
		{[]uint8{0x0C, 0x2B, 0x00, 0xFF, 0xDE, 0xF0}, "CMPI.B #0xFF,(0xDEF0,A3)"},

		// CMPI.W #imm,d16(An) (Compare immediate word to memory with displacement)
		{[]uint8{0x0C, 0x68, 0x00, 0x01, 0x12, 0x34}, "CMPI.W #0x0001,(0x1234,A0)"},
		{[]uint8{0x0C, 0x69, 0x7F, 0xFF, 0x56, 0x78}, "CMPI.W #0x7FFF,(0x5678,A1)"},

		// CMPI.L #imm,d16(An) (Compare immediate long to memory with displacement)
		{[]uint8{0x0C, 0xA8, 0x00, 0x00, 0x00, 0x01, 0x12, 0x34}, "CMPI.L #0x00000001,(0x1234,A0)"},
		{[]uint8{0x0C, 0xA9, 0x7F, 0xFF, 0xFF, 0xFF, 0x56, 0x78}, "CMPI.L #0x7FFFFFFF,(0x5678,A1)"},

		// CMPI.B #imm,d8(An,Xn) (Compare immediate byte to memory with index)
		{[]uint8{0x0C, 0x30, 0x00, 0x01, 0x12, 0x34}, "CMPI.B #0x01,(0x12,A0,D4.W)"},
		{[]uint8{0x0C, 0x31, 0x00, 0x7F, 0x56, 0x70}, "CMPI.B #0x7F,(0x56,A1,D0.W)"},
		{[]uint8{0x0C, 0x32, 0x00, 0x80, 0x9A, 0xB2}, "CMPI.B #0x80,(0x9A,A2,D2.W)"},
		{[]uint8{0x0C, 0x33, 0x00, 0xFF, 0xDE, 0xF7}, "CMPI.B #0xFF,(0xDE,A3,D7.W)"},

		// CMPI.B #imm,d8(An,Xn) with address register index
		{[]uint8{0x0C, 0x30, 0x00, 0x01, 0x12, 0xB4}, "CMPI.B #0x01,(0x12,A0,A4.W)"},
		{[]uint8{0x0C, 0x31, 0x00, 0x7F, 0x56, 0xF0}, "CMPI.B #0x7F,(0x56,A1,A0.W)"},
		{[]uint8{0x0C, 0x32, 0x00, 0x80, 0x9A, 0xB2}, "CMPI.B #0x80,(0x9A,A2,D2.W)"},

		// CMPI.W #imm,d8(An,Xn) (Compare immediate word to memory with index)
		{[]uint8{0x0C, 0x70, 0x00, 0x01, 0x12, 0x34}, "CMPI.W #0x0001,(0x12,A0,D4.W)"},
		{[]uint8{0x0C, 0x71, 0x7F, 0xFF, 0x56, 0x70}, "CMPI.W #0x7FFF,(0x56,A1,D0.W)"},

		// CMPI.W #imm,d8(An,Xn) with address register index
		{[]uint8{0x0C, 0x70, 0x00, 0x01, 0x12, 0xB4}, "CMPI.W #0x0001,(0x12,A0,A4.W)"},
		{[]uint8{0x0C, 0x71, 0x7F, 0xFF, 0x56, 0xF0}, "CMPI.W #0x7FFF,(0x56,A1,A0.W)"},

		// CMPI.L #imm,d8(An,Xn) (Compare immediate long to memory with index)
		{[]uint8{0x0C, 0xB0, 0x00, 0x00, 0x00, 0x01, 0x12, 0x34}, "CMPI.L #0x00000001,(0x12,A0,D4.W)"},
		{[]uint8{0x0C, 0xB1, 0x7F, 0xFF, 0xFF, 0xFF, 0x56, 0x70}, "CMPI.L #0x7FFFFFFF,(0x56,A1,D0.W)"},

		// CMPI.L #imm,d8(An,Xn) with address register index
		{[]uint8{0x0C, 0xB0, 0x00, 0x00, 0x00, 0x01, 0x12, 0xB4}, "CMPI.L #0x00000001,(0x12,A0,A4.W)"},
		{[]uint8{0x0C, 0xB1, 0x7F, 0xFF, 0xFF, 0xFF, 0x56, 0xF0}, "CMPI.L #0x7FFFFFFF,(0x56,A1,A0.W)"},

		// CMPI.B #imm,xxx.W (Compare immediate byte to absolute short address)
		{[]uint8{0x0C, 0x38, 0x00, 0x01, 0x12, 0x34}, "CMPI.B #0x01,(0x1234).W"},
		{[]uint8{0x0C, 0x38, 0x00, 0x7F, 0x56, 0x78}, "CMPI.B #0x7F,(0x5678).W"},
		{[]uint8{0x0C, 0x38, 0x00, 0x80, 0x9A, 0xBC}, "CMPI.B #0x80,(0x9ABC).W"},
		{[]uint8{0x0C, 0x38, 0x00, 0xFF, 0xDE, 0xF0}, "CMPI.B #0xFF,(0xDEF0).W"},

		// CMPI.W #imm,xxx.W (Compare immediate word to absolute short address)
		{[]uint8{0x0C, 0x78, 0x00, 0x01, 0x12, 0x34}, "CMPI.W #0x0001,(0x1234).W"},
		{[]uint8{0x0C, 0x78, 0x7F, 0xFF, 0x56, 0x78}, "CMPI.W #0x7FFF,(0x5678).W"},
		{[]uint8{0x0C, 0x78, 0x80, 0x00, 0x9A, 0xBC}, "CMPI.W #0x8000,(0x9ABC).W"},
		{[]uint8{0x0C, 0x78, 0xFF, 0xFF, 0xDE, 0xF0}, "CMPI.W #0xFFFF,(0xDEF0).W"},

		// CMPI.L #imm,xxx.W (Compare immediate long to absolute short address)
		{[]uint8{0x0C, 0xB8, 0x00, 0x00, 0x00, 0x01, 0x12, 0x34}, "CMPI.L #0x00000001,(0x1234).W"},
		{[]uint8{0x0C, 0xB8, 0x7F, 0xFF, 0xFF, 0xFF, 0x56, 0x78}, "CMPI.L #0x7FFFFFFF,(0x5678).W"},
		{[]uint8{0x0C, 0xB8, 0x80, 0x00, 0x00, 0x00, 0x9A, 0xBC}, "CMPI.L #0x80000000,(0x9ABC).W"},
		{[]uint8{0x0C, 0xB8, 0xFF, 0xFF, 0xFF, 0xFF, 0xDE, 0xF0}, "CMPI.L #0xFFFFFFFF,(0xDEF0).W"},

		// CMPI.B #imm,xxx.L (Compare immediate byte to absolute long address)
		{[]uint8{0x0C, 0x39, 0x00, 0x01, 0x12, 0x34, 0x56, 0x78}, "CMPI.B #0x01,(0x12345678).L"},
		{[]uint8{0x0C, 0x39, 0x00, 0x7F, 0x9A, 0xBC, 0xDE, 0xF0}, "CMPI.B #0x7F,(0x9ABCDEF0).L"},
		{[]uint8{0x0C, 0x39, 0x00, 0x80, 0x00, 0x00, 0x00, 0x01}, "CMPI.B #0x80,(0x00000001).L"},
		{[]uint8{0x0C, 0x39, 0x00, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF}, "CMPI.B #0xFF,(0xFFFFFFFF).L"},

		// CMPI.W #imm,xxx.L (Compare immediate word to absolute long address)
		{[]uint8{0x0C, 0x79, 0x00, 0x01, 0x12, 0x34, 0x56, 0x78}, "CMPI.W #0x0001,(0x12345678).L"},
		{[]uint8{0x0C, 0x79, 0x7F, 0xFF, 0x9A, 0xBC, 0xDE, 0xF0}, "CMPI.W #0x7FFF,(0x9ABCDEF0).L"},

		// CMPI.L #imm,xxx.L (Compare immediate long to absolute long address)
		{[]uint8{0x0C, 0xB9, 0x00, 0x00, 0x00, 0x01, 0x12, 0x34, 0x56, 0x78}, "CMPI.L #0x00000001,(0x12345678).L"},
		{[]uint8{0x0C, 0xB9, 0x7F, 0xFF, 0xFF, 0xFF, 0x9A, 0xBC, 0xDE, 0xF0}, "CMPI.L #0x7FFFFFFF,(0x9ABCDEF0).L"},
	}

	for _, tc := range testCases {
		t.Run(tc.expected, func(t *testing.T) {
			result := DisassembleInstruction(tc.bytes, 0)
			if result != tc.expected {
				t.Errorf("Expected %s, got %s", tc.expected, result)
			}
		})
	}
}
