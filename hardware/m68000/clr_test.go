package m68000

import "testing"

func TestDisassembleCLR(t *testing.T) {
	testCases := []struct {
		bytes    []uint8
		expected string
	}{
		// CLR - Clear an Operand
		// Format: 0100 0010 ss eeeeee
		// Where:
		// - ss is the size (00=byte, 01=word, 10=long)
		// - eeeeee defines the effective address (destination operand)

		// CLR.B Dn (Clear byte in data register)
		{[]uint8{0x42, 0x00}, "CLR.B D0"},
		{[]uint8{0x42, 0x01}, "CLR.B D1"},
		{[]uint8{0x42, 0x02}, "CLR.B D2"},
		{[]uint8{0x42, 0x03}, "CLR.B D3"},
		{[]uint8{0x42, 0x04}, "CLR.B D4"},
		{[]uint8{0x42, 0x05}, "CLR.B D5"},
		{[]uint8{0x42, 0x06}, "CLR.B D6"},
		{[]uint8{0x42, 0x07}, "CLR.B D7"},

		// CLR.W Dn (Clear word in data register)
		{[]uint8{0x42, 0x40}, "CLR.W D0"},
		{[]uint8{0x42, 0x41}, "CLR.W D1"},
		{[]uint8{0x42, 0x42}, "CLR.W D2"},
		{[]uint8{0x42, 0x43}, "CLR.W D3"},
		{[]uint8{0x42, 0x44}, "CLR.W D4"},
		{[]uint8{0x42, 0x45}, "CLR.W D5"},
		{[]uint8{0x42, 0x46}, "CLR.W D6"},
		{[]uint8{0x42, 0x47}, "CLR.W D7"},

		// CLR.L Dn (Clear long word in data register)
		{[]uint8{0x42, 0x80}, "CLR.L D0"},
		{[]uint8{0x42, 0x81}, "CLR.L D1"},
		{[]uint8{0x42, 0x82}, "CLR.L D2"},
		{[]uint8{0x42, 0x83}, "CLR.L D3"},
		{[]uint8{0x42, 0x84}, "CLR.L D4"},
		{[]uint8{0x42, 0x85}, "CLR.L D5"},
		{[]uint8{0x42, 0x86}, "CLR.L D6"},
		{[]uint8{0x42, 0x87}, "CLR.L D7"},

		// CLR.B (An) (Clear byte in memory)
		{[]uint8{0x42, 0x10}, "CLR.B (A0)"},
		{[]uint8{0x42, 0x11}, "CLR.B (A1)"},
		{[]uint8{0x42, 0x12}, "CLR.B (A2)"},
		{[]uint8{0x42, 0x13}, "CLR.B (A3)"},
		{[]uint8{0x42, 0x14}, "CLR.B (A4)"},
		{[]uint8{0x42, 0x15}, "CLR.B (A5)"},
		{[]uint8{0x42, 0x16}, "CLR.B (A6)"},
		{[]uint8{0x42, 0x17}, "CLR.B (A7)"},

		// CLR.W (An) (Clear word in memory)
		{[]uint8{0x42, 0x50}, "CLR.W (A0)"},
		{[]uint8{0x42, 0x51}, "CLR.W (A1)"},
		{[]uint8{0x42, 0x52}, "CLR.W (A2)"},
		{[]uint8{0x42, 0x53}, "CLR.W (A3)"},
		{[]uint8{0x42, 0x54}, "CLR.W (A4)"},
		{[]uint8{0x42, 0x55}, "CLR.W (A5)"},
		{[]uint8{0x42, 0x56}, "CLR.W (A6)"},
		{[]uint8{0x42, 0x57}, "CLR.W (A7)"},

		// CLR.L (An) (Clear long word in memory)
		{[]uint8{0x42, 0x90}, "CLR.L (A0)"},
		{[]uint8{0x42, 0x91}, "CLR.L (A1)"},
		{[]uint8{0x42, 0x92}, "CLR.L (A2)"},
		{[]uint8{0x42, 0x93}, "CLR.L (A3)"},
		{[]uint8{0x42, 0x94}, "CLR.L (A4)"},
		{[]uint8{0x42, 0x95}, "CLR.L (A5)"},
		{[]uint8{0x42, 0x96}, "CLR.L (A6)"},
		{[]uint8{0x42, 0x97}, "CLR.L (A7)"},

		// CLR.B (An)+ (Clear byte in memory with postincrement)
		{[]uint8{0x42, 0x18}, "CLR.B (A0)+"},
		{[]uint8{0x42, 0x19}, "CLR.B (A1)+"},
		{[]uint8{0x42, 0x1A}, "CLR.B (A2)+"},
		{[]uint8{0x42, 0x1B}, "CLR.B (A3)+"},
		{[]uint8{0x42, 0x1C}, "CLR.B (A4)+"},
		{[]uint8{0x42, 0x1D}, "CLR.B (A5)+"},
		{[]uint8{0x42, 0x1E}, "CLR.B (A6)+"},
		{[]uint8{0x42, 0x1F}, "CLR.B (A7)+"},

		// CLR.W (An)+ (Clear word in memory with postincrement)
		{[]uint8{0x42, 0x58}, "CLR.W (A0)+"},
		{[]uint8{0x42, 0x59}, "CLR.W (A1)+"},
		{[]uint8{0x42, 0x5A}, "CLR.W (A2)+"},
		{[]uint8{0x42, 0x5B}, "CLR.W (A3)+"},
		{[]uint8{0x42, 0x5C}, "CLR.W (A4)+"},
		{[]uint8{0x42, 0x5D}, "CLR.W (A5)+"},
		{[]uint8{0x42, 0x5E}, "CLR.W (A6)+"},
		{[]uint8{0x42, 0x5F}, "CLR.W (A7)+"},

		// CLR.L (An)+ (Clear long word in memory with postincrement)
		{[]uint8{0x42, 0x98}, "CLR.L (A0)+"},
		{[]uint8{0x42, 0x99}, "CLR.L (A1)+"},
		{[]uint8{0x42, 0x9A}, "CLR.L (A2)+"},
		{[]uint8{0x42, 0x9B}, "CLR.L (A3)+"},
		{[]uint8{0x42, 0x9C}, "CLR.L (A4)+"},
		{[]uint8{0x42, 0x9D}, "CLR.L (A5)+"},
		{[]uint8{0x42, 0x9E}, "CLR.L (A6)+"},
		{[]uint8{0x42, 0x9F}, "CLR.L (A7)+"},

		// CLR.B -(An) (Clear byte in memory with predecrement)
		{[]uint8{0x42, 0x20}, "CLR.B -(A0)"},
		{[]uint8{0x42, 0x21}, "CLR.B -(A1)"},
		{[]uint8{0x42, 0x22}, "CLR.B -(A2)"},
		{[]uint8{0x42, 0x23}, "CLR.B -(A3)"},
		{[]uint8{0x42, 0x24}, "CLR.B -(A4)"},
		{[]uint8{0x42, 0x25}, "CLR.B -(A5)"},
		{[]uint8{0x42, 0x26}, "CLR.B -(A6)"},
		{[]uint8{0x42, 0x27}, "CLR.B -(A7)"},

		// CLR.W -(An) (Clear word in memory with predecrement)
		{[]uint8{0x42, 0x60}, "CLR.W -(A0)"},
		{[]uint8{0x42, 0x61}, "CLR.W -(A1)"},
		{[]uint8{0x42, 0x62}, "CLR.W -(A2)"},
		{[]uint8{0x42, 0x63}, "CLR.W -(A3)"},
		{[]uint8{0x42, 0x64}, "CLR.W -(A4)"},
		{[]uint8{0x42, 0x65}, "CLR.W -(A5)"},
		{[]uint8{0x42, 0x66}, "CLR.W -(A6)"},
		{[]uint8{0x42, 0x67}, "CLR.W -(A7)"},

		// CLR.L -(An) (Clear long word in memory with predecrement)
		{[]uint8{0x42, 0xA0}, "CLR.L -(A0)"},
		{[]uint8{0x42, 0xA1}, "CLR.L -(A1)"},
		{[]uint8{0x42, 0xA2}, "CLR.L -(A2)"},
		{[]uint8{0x42, 0xA3}, "CLR.L -(A3)"},
		{[]uint8{0x42, 0xA4}, "CLR.L -(A4)"},
		{[]uint8{0x42, 0xA5}, "CLR.L -(A5)"},
		{[]uint8{0x42, 0xA6}, "CLR.L -(A6)"},
		{[]uint8{0x42, 0xA7}, "CLR.L -(A7)"},

		// CLR.B d16(An) (Clear byte in memory with displacement)
		{[]uint8{0x42, 0x28, 0x12, 0x34}, "CLR.B (0x1234,A0)"},
		{[]uint8{0x42, 0x29, 0x56, 0x78}, "CLR.B (0x5678,A1)"},
		{[]uint8{0x42, 0x2A, 0x9A, 0xBC}, "CLR.B (0x9ABC,A2)"},
		{[]uint8{0x42, 0x2B, 0xDE, 0xF0}, "CLR.B (0xDEF0,A3)"},
		{[]uint8{0x42, 0x2C, 0x00, 0x01}, "CLR.B (0x0001,A4)"},
		{[]uint8{0x42, 0x2D, 0x00, 0x00}, "CLR.B (0x0000,A5)"},
		{[]uint8{0x42, 0x2E, 0xFF, 0xFF}, "CLR.B (0xFFFF,A6)"},
		{[]uint8{0x42, 0x2F, 0x80, 0x00}, "CLR.B (0x8000,A7)"},

		// CLR.W d16(An) (Clear word in memory with displacement)
		{[]uint8{0x42, 0x68, 0x12, 0x34}, "CLR.W (0x1234,A0)"},
		{[]uint8{0x42, 0x69, 0x56, 0x78}, "CLR.W (0x5678,A1)"},
		{[]uint8{0x42, 0x6A, 0x9A, 0xBC}, "CLR.W (0x9ABC,A2)"},
		{[]uint8{0x42, 0x6B, 0xDE, 0xF0}, "CLR.W (0xDEF0,A3)"},
		{[]uint8{0x42, 0x6C, 0x00, 0x01}, "CLR.W (0x0001,A4)"},
		{[]uint8{0x42, 0x6D, 0x00, 0x00}, "CLR.W (0x0000,A5)"},
		{[]uint8{0x42, 0x6E, 0xFF, 0xFF}, "CLR.W (0xFFFF,A6)"},
		{[]uint8{0x42, 0x6F, 0x80, 0x00}, "CLR.W (0x8000,A7)"},

		// CLR.L d16(An) (Clear long word in memory with displacement)
		{[]uint8{0x42, 0xA8, 0x12, 0x34}, "CLR.L (0x1234,A0)"},
		{[]uint8{0x42, 0xA9, 0x56, 0x78}, "CLR.L (0x5678,A1)"},
		{[]uint8{0x42, 0xAA, 0x9A, 0xBC}, "CLR.L (0x9ABC,A2)"},
		{[]uint8{0x42, 0xAB, 0xDE, 0xF0}, "CLR.L (0xDEF0,A3)"},
		{[]uint8{0x42, 0xAC, 0x00, 0x01}, "CLR.L (0x0001,A4)"},
		{[]uint8{0x42, 0xAD, 0x00, 0x00}, "CLR.L (0x0000,A5)"},
		{[]uint8{0x42, 0xAE, 0xFF, 0xFF}, "CLR.L (0xFFFF,A6)"},
		{[]uint8{0x42, 0xAF, 0x80, 0x00}, "CLR.L (0x8000,A7)"},

		// CLR.B d8(An,Xn) (Clear byte in memory with index)
		{[]uint8{0x42, 0x30, 0x12, 0x34}, "CLR.B (0x12,A0,D4.W)"},
		{[]uint8{0x42, 0x31, 0x56, 0x70}, "CLR.B (0x56,A1,D0.W)"},
		{[]uint8{0x42, 0x32, 0x9A, 0xB1}, "CLR.B (0x9A,A2,D1.W)"},
		{[]uint8{0x42, 0x33, 0xDE, 0xF2}, "CLR.B (0xDE,A3,D2.W)"},
		{[]uint8{0x42, 0x34, 0x12, 0x83}, "CLR.B (0x12,A4,D3.L)"},
		{[]uint8{0x42, 0x35, 0x56, 0x75}, "CLR.B (0x56,A5,D5.W)"},
		{[]uint8{0x42, 0x36, 0x9A, 0xF6}, "CLR.B (0x9A,A6,D6.L)"},
		{[]uint8{0x42, 0x37, 0xDE, 0x77}, "CLR.B (0xDE,A7,D7.W)"},

		// CLR.B d8(An,Xn) with address register index
		{[]uint8{0x42, 0x30, 0x12, 0xB4}, "CLR.B (0x12,A0,A4.W)"},
		{[]uint8{0x42, 0x31, 0x56, 0xF0}, "CLR.B (0x56,A1,A0.W)"},
		{[]uint8{0x42, 0x32, 0x9A, 0xB1}, "CLR.B (0x9A,A2,D1.W)"},

		// CLR.W d8(An,Xn) (Clear word in memory with index)
		{[]uint8{0x42, 0x70, 0x12, 0x34}, "CLR.W (0x12,A0,D4.W)"},
		{[]uint8{0x42, 0x71, 0x56, 0x70}, "CLR.W (0x56,A1,D0.W)"},
		{[]uint8{0x42, 0x72, 0x9A, 0xB1}, "CLR.W (0x9A,A2,D1.W)"},

		// CLR.L d8(An,Xn) (Clear long word in memory with index)
		{[]uint8{0x42, 0xB0, 0x12, 0x34}, "CLR.L (0x12,A0,D4.W)"},
		{[]uint8{0x42, 0xB1, 0x56, 0x70}, "CLR.L (0x56,A1,D0.W)"},
		{[]uint8{0x42, 0xB2, 0x9A, 0xB1}, "CLR.L (0x9A,A2,D1.W)"},

		// CLR.B xxx.W (Clear byte at absolute short address)
		{[]uint8{0x42, 0x38, 0x12, 0x34}, "CLR.B (0x1234).W"},
		{[]uint8{0x42, 0x38, 0x56, 0x78}, "CLR.B (0x5678).W"},
		{[]uint8{0x42, 0x38, 0x9A, 0xBC}, "CLR.B (0x9ABC).W"},
		{[]uint8{0x42, 0x38, 0xDE, 0xF0}, "CLR.B (0xDEF0).W"},
		{[]uint8{0x42, 0x38, 0x00, 0x00}, "CLR.B (0x0000).W"},
		{[]uint8{0x42, 0x38, 0xFF, 0xFF}, "CLR.B (0xFFFF).W"},

		// CLR.W xxx.W (Clear word at absolute short address)
		{[]uint8{0x42, 0x78, 0x12, 0x34}, "CLR.W (0x1234).W"},
		{[]uint8{0x42, 0x78, 0x56, 0x78}, "CLR.W (0x5678).W"},
		{[]uint8{0x42, 0x78, 0x9A, 0xBC}, "CLR.W (0x9ABC).W"},

		// CLR.L xxx.W (Clear long word at absolute short address)
		{[]uint8{0x42, 0xB8, 0x12, 0x34}, "CLR.L (0x1234).W"},
		{[]uint8{0x42, 0xB8, 0x56, 0x78}, "CLR.L (0x5678).W"},
		{[]uint8{0x42, 0xB8, 0x9A, 0xBC}, "CLR.L (0x9ABC).W"},

		// CLR.B xxx.L (Clear byte at absolute long address)
		{[]uint8{0x42, 0x39, 0x12, 0x34, 0x56, 0x78}, "CLR.B (0x12345678).L"},
		{[]uint8{0x42, 0x39, 0x9A, 0xBC, 0xDE, 0xF0}, "CLR.B (0x9ABCDEF0).L"},
		{[]uint8{0x42, 0x39, 0x00, 0x00, 0x00, 0x00}, "CLR.B (0x00000000).L"},
		{[]uint8{0x42, 0x39, 0xFF, 0xFF, 0xFF, 0xFF}, "CLR.B (0xFFFFFFFF).L"},

		// CLR.W xxx.L (Clear word at absolute long address)
		{[]uint8{0x42, 0x79, 0x12, 0x34, 0x56, 0x78}, "CLR.W (0x12345678).L"},
		{[]uint8{0x42, 0x79, 0x9A, 0xBC, 0xDE, 0xF0}, "CLR.W (0x9ABCDEF0).L"},

		// CLR.L xxx.L (Clear long word at absolute long address)
		{[]uint8{0x42, 0xB9, 0x12, 0x34, 0x56, 0x78}, "CLR.L (0x12345678).L"},
		{[]uint8{0x42, 0xB9, 0x9A, 0xBC, 0xDE, 0xF0}, "CLR.L (0x9ABCDEF0).L"},
	}

	for _, tc := range testCases {
		t.Run(tc.expected, func(t *testing.T) {
			result := DisassembleInstruction(tc.bytes, 0)
			if result != tc.expected {
				t.Errorf("Expected %s, got %s", tc.expected, result)
			}
		})
	}
}
