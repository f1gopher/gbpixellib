package m68000

import "testing"

func TestDisassembleCHK(t *testing.T) {
	testCases := []testCase{
		// CHK - Check Register Against Bounds
		// Format: 0100 rrr 1s0 eee mmm
		// Where:
		// - rrr is the register number (D0-D7)
		// - s is the size (0=word, 1=long for 68020+)
		// - eee mmm define the effective address mode

		// The 68000 only supports CHK.W (word size, s=0)
		// CHK.L was added in the 68020

		// CHK.W Dn,Dn (Check data register against data register bounds)
		{[]uint8{0x41, 0x80}, "CHK.W D0,D0"},
		{[]uint8{0x43, 0x81}, "CHK.W D1,D1"},
		{[]uint8{0x45, 0x82}, "CHK.W D2,D2"},
		{[]uint8{0x47, 0x83}, "CHK.W D3,D3"},
		{[]uint8{0x49, 0x84}, "CHK.W D4,D4"},
		{[]uint8{0x4B, 0x85}, "CHK.W D5,D5"},
		{[]uint8{0x4D, 0x86}, "CHK.W D6,D6"},
		{[]uint8{0x4F, 0x87}, "CHK.W D7,D7"},

		// Cross register tests
		{[]uint8{0x41, 0x87}, "CHK.W D7,D0"}, // Check D7 against bound in D0
		{[]uint8{0x43, 0x86}, "CHK.W D6,D1"}, // Check D6 against bound in D1
		{[]uint8{0x45, 0x85}, "CHK.W D5,D2"}, // Check D5 against bound in D2
		{[]uint8{0x47, 0x84}, "CHK.W D4,D3"}, // Check D4 against bound in D3
		{[]uint8{0x49, 0x83}, "CHK.W D3,D4"}, // Check D3 against bound in D4
		{[]uint8{0x4B, 0x82}, "CHK.W D2,D5"}, // Check D2 against bound in D5
		{[]uint8{0x4D, 0x81}, "CHK.W D1,D6"}, // Check D1 against bound in D6
		{[]uint8{0x4F, 0x80}, "CHK.W D0,D7"}, // Check D0 against bound in D7

		// CHK.W (An),Dn (Check data register against memory bounds)
		{[]uint8{0x41, 0x90}, "CHK.W (A0),D0"},
		{[]uint8{0x43, 0x91}, "CHK.W (A1),D1"},
		{[]uint8{0x45, 0x92}, "CHK.W (A2),D2"},
		{[]uint8{0x47, 0x93}, "CHK.W (A3),D3"},
		{[]uint8{0x49, 0x94}, "CHK.W (A4),D4"},
		{[]uint8{0x4B, 0x95}, "CHK.W (A5),D5"},
		{[]uint8{0x4D, 0x96}, "CHK.W (A6),D6"},
		{[]uint8{0x4F, 0x97}, "CHK.W (A7),D7"},

		// CHK.W (An)+,Dn (Check data register against memory bounds with postincrement)
		{[]uint8{0x41, 0x98}, "CHK.W (A0)+,D0"},
		{[]uint8{0x43, 0x99}, "CHK.W (A1)+,D1"},
		{[]uint8{0x45, 0x9A}, "CHK.W (A2)+,D2"},
		{[]uint8{0x47, 0x9B}, "CHK.W (A3)+,D3"},
		{[]uint8{0x49, 0x9C}, "CHK.W (A4)+,D4"},
		{[]uint8{0x4B, 0x9D}, "CHK.W (A5)+,D5"},
		{[]uint8{0x4D, 0x9E}, "CHK.W (A6)+,D6"},
		{[]uint8{0x4F, 0x9F}, "CHK.W (A7)+,D7"},

		// CHK.W -(An),Dn (Check data register against memory bounds with predecrement)
		{[]uint8{0x41, 0xA0}, "CHK.W -(A0),D0"},
		{[]uint8{0x43, 0xA1}, "CHK.W -(A1),D1"},
		{[]uint8{0x45, 0xA2}, "CHK.W -(A2),D2"},
		{[]uint8{0x47, 0xA3}, "CHK.W -(A3),D3"},
		{[]uint8{0x49, 0xA4}, "CHK.W -(A4),D4"},
		{[]uint8{0x4B, 0xA5}, "CHK.W -(A5),D5"},
		{[]uint8{0x4D, 0xA6}, "CHK.W -(A6),D6"},
		{[]uint8{0x4F, 0xA7}, "CHK.W -(A7),D7"},

		// CHK.W d16(An),Dn (Check data register against memory bounds with displacement)
		{[]uint8{0x41, 0xA8, 0x12, 0x34}, "CHK.W (0x1234,A0),D0"},
		{[]uint8{0x43, 0xA9, 0x56, 0x78}, "CHK.W (0x5678,A1),D1"},
		{[]uint8{0x45, 0xAA, 0x9A, 0xBC}, "CHK.W (0x9ABC,A2),D2"},
		{[]uint8{0x47, 0xAB, 0xDE, 0xF0}, "CHK.W (0xDEF0,A3),D3"},
		{[]uint8{0x49, 0xAC, 0x00, 0x10}, "CHK.W (0x0010,A4),D4"},
		{[]uint8{0x4B, 0xAD, 0x01, 0x00}, "CHK.W (0x0100,A5),D5"},
		{[]uint8{0x4D, 0xAE, 0x10, 0x00}, "CHK.W (0x1000,A6),D6"},
		{[]uint8{0x4F, 0xAF, 0xFF, 0xFF}, "CHK.W (0xFFFF,A7),D7"},

		// CHK.W d8(An,Xn),Dn (Check data register against memory bounds with index)
		{[]uint8{0x41, 0xB0, 0x12, 0x34}, "CHK.W (0x12,A0,D4.W),D0"},
		{[]uint8{0x43, 0xB1, 0x56, 0x70}, "CHK.W (0x56,A1,D0.W),D1"},
		{[]uint8{0x45, 0xB2, 0x9A, 0xB1}, "CHK.W (0x9A,A2,D1.W),D2"},
		{[]uint8{0x47, 0xB3, 0xDE, 0xF2}, "CHK.W (0xDE,A3,D2.W),D3"},
		{[]uint8{0x49, 0xB4, 0x00, 0x13}, "CHK.W (0x00,A4,D3.W),D4"},
		{[]uint8{0x4B, 0xB5, 0x01, 0x05}, "CHK.W (0x01,A5,D5.W),D5"},
		{[]uint8{0x4D, 0xB6, 0x10, 0x06}, "CHK.W (0x10,A6,D6.W),D6"},
		{[]uint8{0x4F, 0xB7, 0xFF, 0x07}, "CHK.W (0xFF,A7,D7.W),D7"},

		// CHK.W d8(An,Xn),Dn with address register index
		{[]uint8{0x41, 0xB0, 0x12, 0xB4}, "CHK.W (0x12,A0,A4.W),D0"},
		{[]uint8{0x43, 0xB2, 0x34, 0xF6}, "CHK.W (0x34,A2,A6.W),D1"},

		// CHK.W xxx.W,Dn (Check data register against absolute short address bounds)
		{[]uint8{0x41, 0xB8, 0x12, 0x34}, "CHK.W (0x1234).W,D0"},
		{[]uint8{0x43, 0xB8, 0x56, 0x78}, "CHK.W (0x5678).W,D1"},
		{[]uint8{0x45, 0xB8, 0x9A, 0xBC}, "CHK.W (0x9ABC).W,D2"},
		{[]uint8{0x47, 0xB8, 0xDE, 0xF0}, "CHK.W (0xDEF0).W,D3"},
		{[]uint8{0x49, 0xB8, 0x00, 0x00}, "CHK.W (0x0000).W,D4"},
		{[]uint8{0x4B, 0xB8, 0xFF, 0xFF}, "CHK.W (0xFFFF).W,D5"},

		// CHK.W xxx.L,Dn (Check data register against absolute long address bounds)
		{[]uint8{0x41, 0xB9, 0x12, 0x34, 0x56, 0x78}, "CHK.W (0x12345678).L,D0"},
		{[]uint8{0x43, 0xB9, 0x9A, 0xBC, 0xDE, 0xF0}, "CHK.W (0x9ABCDEF0).L,D1"},
		{[]uint8{0x45, 0xB9, 0x00, 0x00, 0x00, 0x00}, "CHK.W (0x00000000).L,D2"},
		{[]uint8{0x47, 0xB9, 0xFF, 0xFF, 0xFF, 0xFF}, "CHK.W (0xFFFFFFFF).L,D3"},

		// CHK.W d16(PC),Dn (Check data register against PC-relative bounds)
		{[]uint8{0x41, 0xBA, 0x12, 0x34}, "CHK.W (0x1234,PC),D0"},
		{[]uint8{0x43, 0xBA, 0x56, 0x78}, "CHK.W (0x5678,PC),D1"},
		{[]uint8{0x45, 0xBA, 0xFF, 0xFE}, "CHK.W (0xFFFE,PC),D2"},
		{[]uint8{0x47, 0xBA, 0x00, 0x02}, "CHK.W (0x0002,PC),D3"},

		// CHK.W d8(PC,Xn),Dn (Check data register against PC-relative with index bounds)
		{[]uint8{0x41, 0xBB, 0x12, 0x34}, "CHK.W (0x12,PC,D4.W),D0"},
		{[]uint8{0x43, 0xBB, 0x56, 0x70}, "CHK.W (0x56,PC,D0.W),D1"},
		{[]uint8{0x45, 0xBB, 0x9A, 0xB1}, "CHK.W (0x9A,PC,D1.W),D2"},
		{[]uint8{0x41, 0xBB, 0x12, 0xB4}, "CHK.W (0x12,PC,A4.W),D0"},
		{[]uint8{0x43, 0xBB, 0x56, 0xF0}, "CHK.W (0x56,PC,A0.W),D1"},

		// CHK.W #<data>,Dn (Check data register against immediate bounds)
		{[]uint8{0x41, 0xBC, 0x12, 0x34}, "CHK.W #0x1234,D0"},
		{[]uint8{0x43, 0xBC, 0x56, 0x78}, "CHK.W #0x5678,D1"},
		{[]uint8{0x45, 0xBC, 0x9A, 0xBC}, "CHK.W #0x9ABC,D2"},
		{[]uint8{0x47, 0xBC, 0xDE, 0xF0}, "CHK.W #0xDEF0,D3"},
		{[]uint8{0x49, 0xBC, 0x7F, 0xFF}, "CHK.W #0x7FFF,D4"}, // Maximum positive value
		{[]uint8{0x4B, 0xBC, 0x80, 0x00}, "CHK.W #0x8000,D5"}, // Minimum negative value
		{[]uint8{0x4D, 0xBC, 0x00, 0x00}, "CHK.W #0x0000,D6"}, // Zero
		{[]uint8{0x4F, 0xBC, 0xFF, 0xFF}, "CHK.W #0xFFFF,D7"}, // -1
	}

	runTests(t, testCases)
}
