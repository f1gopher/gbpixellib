package m68000

import "testing"

func TestDisassembleADDI(t *testing.T) {
	testCases := []struct {
		bytes    []uint8
		expected string
	}{
		// ADDI - Add Immediate
		// Operation: Immediate Data + Destination → Destination
		// Sizes: Byte (00), Word (01), Long (10)

		// ADDI.B #imm,Dn
		{[]uint8{0x06, 0x00, 0x00, 0x01}, "ADDI.B #0x01,D0"},
		{[]uint8{0x06, 0x01, 0x00, 0x7F}, "ADDI.B #0x7F,D1"},
		{[]uint8{0x06, 0x02, 0x00, 0xFF}, "ADDI.B #0xFF,D2"},
		{[]uint8{0x06, 0x03, 0x00, 0x12}, "ADDI.B #0x12,D3"},
		{[]uint8{0x06, 0x04, 0x00, 0x34}, "ADDI.B #0x34,D4"},
		{[]uint8{0x06, 0x05, 0x00, 0x56}, "ADDI.B #0x56,D5"},
		{[]uint8{0x06, 0x06, 0x00, 0x78}, "ADDI.B #0x78,D6"},
		{[]uint8{0x06, 0x07, 0x00, 0x9A}, "ADDI.B #0x9A,D7"},

		// ADDI.W #imm,Dn
		{[]uint8{0x06, 0x40, 0x00, 0x01}, "ADDI.W #0x0001,D0"},
		{[]uint8{0x06, 0x41, 0x7F, 0xFF}, "ADDI.W #0x7FFF,D1"},
		{[]uint8{0x06, 0x42, 0xFF, 0xFF}, "ADDI.W #0xFFFF,D2"},
		{[]uint8{0x06, 0x43, 0x12, 0x34}, "ADDI.W #0x1234,D3"},
		{[]uint8{0x06, 0x44, 0x56, 0x78}, "ADDI.W #0x5678,D4"},
		{[]uint8{0x06, 0x45, 0x9A, 0xBC}, "ADDI.W #0x9ABC,D5"},
		{[]uint8{0x06, 0x46, 0xDE, 0xF0}, "ADDI.W #0xDEF0,D6"},
		{[]uint8{0x06, 0x47, 0x80, 0x00}, "ADDI.W #0x8000,D7"},

		// ADDI.L #imm,Dn
		{[]uint8{0x06, 0x80, 0x00, 0x00, 0x00, 0x01}, "ADDI.L #0x00000001,D0"},
		{[]uint8{0x06, 0x81, 0x7F, 0xFF, 0xFF, 0xFF}, "ADDI.L #0x7FFFFFFF,D1"},
		{[]uint8{0x06, 0x82, 0xFF, 0xFF, 0xFF, 0xFF}, "ADDI.L #0xFFFFFFFF,D2"},
		{[]uint8{0x06, 0x83, 0x12, 0x34, 0x56, 0x78}, "ADDI.L #0x12345678,D3"},
		{[]uint8{0x06, 0x84, 0x9A, 0xBC, 0xDE, 0xF0}, "ADDI.L #0x9ABCDEF0,D4"},
		{[]uint8{0x06, 0x85, 0x00, 0x11, 0x22, 0x33}, "ADDI.L #0x00112233,D5"},
		{[]uint8{0x06, 0x86, 0x44, 0x55, 0x66, 0x77}, "ADDI.L #0x44556677,D6"},
		{[]uint8{0x06, 0x87, 0x80, 0x00, 0x00, 0x00}, "ADDI.L #0x80000000,D7"},

		// ADDI.B #imm,(An)
		{[]uint8{0x06, 0x10, 0x00, 0x01}, "ADDI.B #0x01,(A0)"},
		{[]uint8{0x06, 0x11, 0x00, 0x7F}, "ADDI.B #0x7F,(A1)"},
		{[]uint8{0x06, 0x12, 0x00, 0xFF}, "ADDI.B #0xFF,(A2)"},
		{[]uint8{0x06, 0x13, 0x00, 0x12}, "ADDI.B #0x12,(A3)"},
		{[]uint8{0x06, 0x14, 0x00, 0x34}, "ADDI.B #0x34,(A4)"},
		{[]uint8{0x06, 0x15, 0x00, 0x56}, "ADDI.B #0x56,(A5)"},
		{[]uint8{0x06, 0x16, 0x00, 0x78}, "ADDI.B #0x78,(A6)"},
		{[]uint8{0x06, 0x17, 0x00, 0x9A}, "ADDI.B #0x9A,(A7)"},

		// ADDI.W #imm,(An)
		{[]uint8{0x06, 0x50, 0x00, 0x01}, "ADDI.W #0x0001,(A0)"},
		{[]uint8{0x06, 0x51, 0x7F, 0xFF}, "ADDI.W #0x7FFF,(A1)"},
		{[]uint8{0x06, 0x52, 0xFF, 0xFF}, "ADDI.W #0xFFFF,(A2)"},
		{[]uint8{0x06, 0x53, 0x12, 0x34}, "ADDI.W #0x1234,(A3)"},
		{[]uint8{0x06, 0x54, 0x56, 0x78}, "ADDI.W #0x5678,(A4)"},
		{[]uint8{0x06, 0x55, 0x9A, 0xBC}, "ADDI.W #0x9ABC,(A5)"},
		{[]uint8{0x06, 0x56, 0xDE, 0xF0}, "ADDI.W #0xDEF0,(A6)"},
		{[]uint8{0x06, 0x57, 0x80, 0x00}, "ADDI.W #0x8000,(A7)"},

		// ADDI.L #imm,(An)
		{[]uint8{0x06, 0x90, 0x00, 0x00, 0x00, 0x01}, "ADDI.L #0x00000001,(A0)"},
		{[]uint8{0x06, 0x91, 0x7F, 0xFF, 0xFF, 0xFF}, "ADDI.L #0x7FFFFFFF,(A1)"},
		{[]uint8{0x06, 0x92, 0xFF, 0xFF, 0xFF, 0xFF}, "ADDI.L #0xFFFFFFFF,(A2)"},
		{[]uint8{0x06, 0x93, 0x12, 0x34, 0x56, 0x78}, "ADDI.L #0x12345678,(A3)"},
		{[]uint8{0x06, 0x94, 0x9A, 0xBC, 0xDE, 0xF0}, "ADDI.L #0x9ABCDEF0,(A4)"},
		{[]uint8{0x06, 0x95, 0x00, 0x11, 0x22, 0x33}, "ADDI.L #0x00112233,(A5)"},
		{[]uint8{0x06, 0x96, 0x44, 0x55, 0x66, 0x77}, "ADDI.L #0x44556677,(A6)"},
		{[]uint8{0x06, 0x97, 0x80, 0x00, 0x00, 0x00}, "ADDI.L #0x80000000,(A7)"},

		// ADDI.B #imm,(An)+
		{[]uint8{0x06, 0x18, 0x00, 0x01}, "ADDI.B #0x01,(A0)+"},
		{[]uint8{0x06, 0x19, 0x00, 0xFF}, "ADDI.B #0xFF,(A1)+"},
		{[]uint8{0x06, 0x1F, 0x00, 0x55}, "ADDI.B #0x55,(A7)+"},

		// ADDI.W #imm,(An)+
		{[]uint8{0x06, 0x58, 0x12, 0x34}, "ADDI.W #0x1234,(A0)+"},
		{[]uint8{0x06, 0x5B, 0xAB, 0xCD}, "ADDI.W #0xABCD,(A3)+"},
		{[]uint8{0x06, 0x5F, 0x77, 0x77}, "ADDI.W #0x7777,(A7)+"},

		// ADDI.L #imm,(An)+
		{[]uint8{0x06, 0x98, 0x12, 0x34, 0x56, 0x78}, "ADDI.L #0x12345678,(A0)+"},
		{[]uint8{0x06, 0x9C, 0xAB, 0xCD, 0xEF, 0x01}, "ADDI.L #0xABCDEF01,(A4)+"},
		{[]uint8{0x06, 0x9F, 0x77, 0x77, 0x77, 0x77}, "ADDI.L #0x77777777,(A7)+"},

		// ADDI.B #imm,-(An)
		{[]uint8{0x06, 0x20, 0x00, 0x01}, "ADDI.B #0x01,-(A0)"},
		{[]uint8{0x06, 0x24, 0x00, 0xFF}, "ADDI.B #0xFF,-(A4)"},
		{[]uint8{0x06, 0x27, 0x00, 0x55}, "ADDI.B #0x55,-(A7)"},

		// ADDI.W #imm,-(An)
		{[]uint8{0x06, 0x60, 0x12, 0x34}, "ADDI.W #0x1234,-(A0)"},
		{[]uint8{0x06, 0x63, 0xAB, 0xCD}, "ADDI.W #0xABCD,-(A3)"},
		{[]uint8{0x06, 0x67, 0x77, 0x77}, "ADDI.W #0x7777,-(A7)"},

		// ADDI.L #imm,-(An)
		{[]uint8{0x06, 0xA0, 0x12, 0x34, 0x56, 0x78}, "ADDI.L #0x12345678,-(A0)"},
		{[]uint8{0x06, 0xA4, 0xAB, 0xCD, 0xEF, 0x01}, "ADDI.L #0xABCDEF01,-(A4)"},
		{[]uint8{0x06, 0xA7, 0x77, 0x77, 0x77, 0x77}, "ADDI.L #0x77777777,-(A7)"},

		// ADDI.B #imm,d16(An)
		{[]uint8{0x06, 0x28, 0x00, 0x01, 0x00, 0x10}, "ADDI.B #0x01,(0x0010,A0)"},
		{[]uint8{0x06, 0x2C, 0x00, 0xFF, 0x12, 0x34}, "ADDI.B #0xFF,(0x1234,A4)"},
		{[]uint8{0x06, 0x2F, 0x00, 0x55, 0xFF, 0xFE}, "ADDI.B #0x55,(0xFFFE,A7)"},

		// ADDI.W #imm,d16(An)
		{[]uint8{0x06, 0x68, 0x12, 0x34, 0x00, 0x10}, "ADDI.W #0x1234,(0x0010,A0)"},
		{[]uint8{0x06, 0x6C, 0xAB, 0xCD, 0x12, 0x34}, "ADDI.W #0xABCD,(0x1234,A4)"},
		{[]uint8{0x06, 0x6F, 0x77, 0x77, 0xFF, 0xFE}, "ADDI.W #0x7777,(0xFFFE,A7)"},

		// ADDI.L #imm,d16(An)
		{[]uint8{0x06, 0xA8, 0x12, 0x34, 0x56, 0x78, 0x00, 0x10}, "ADDI.L #0x12345678,(0x0010,A0)"},
		{[]uint8{0x06, 0xAC, 0xAB, 0xCD, 0xEF, 0x01, 0x12, 0x34}, "ADDI.L #0xABCDEF01,(0x1234,A4)"},
		{[]uint8{0x06, 0xAF, 0x77, 0x77, 0x77, 0x77, 0xFF, 0xFE}, "ADDI.L #0x77777777,(0xFFFE,A7)"},

		// ADDI.B #imm,d8(An,Xn)
		{[]uint8{0x06, 0x30, 0x00, 0x01, 0x12, 0x34}, "ADDI.B #0x01,(0x12,A0,D4.W)"},
		{[]uint8{0x06, 0x34, 0x00, 0xFF, 0x56, 0x78}, "ADDI.B #0xFF,(0x56,A4,D7.W)"},
		{[]uint8{0x06, 0x37, 0x00, 0x55, 0x91, 0x00}, "ADDI.B #0x55,(0x91,A7,D0.W)"},
		{[]uint8{0x06, 0x30, 0x00, 0x01, 0x12, 0xB4}, "ADDI.B #0x01,(0x12,A0,A4.W)"},
		{[]uint8{0x06, 0x34, 0x00, 0xFF, 0x56, 0xF8}, "ADDI.B #0xFF,(0x56,A4,A7.W)"},
		{[]uint8{0x06, 0x37, 0x00, 0x55, 0x91, 0x30}, "ADDI.B #0x55,(0x91,A7,A0.W)"},

		// ADDI.W #imm,d8(An,Xn)
		{[]uint8{0x06, 0x70, 0x12, 0x34, 0x12, 0x34}, "ADDI.W #0x1234,(0x12,A0,D4.W)"},
		{[]uint8{0x06, 0x74, 0xAB, 0xCD, 0x56, 0x78}, "ADDI.W #0xABCD,(0x56,A4,D7.W)"},
		{[]uint8{0x06, 0x77, 0x77, 0x77, 0x91, 0x80}, "ADDI.W #0x7777,(0x91,A7,D0.L)"},
		{[]uint8{0x06, 0x70, 0x12, 0x34, 0x12, 0xB4}, "ADDI.W #0x1234,(0x12,A0,A4.W)"},
		{[]uint8{0x06, 0x74, 0xAB, 0xCD, 0x56, 0xF8}, "ADDI.W #0xABCD,(0x56,A4,A7.W)"},
		{[]uint8{0x06, 0x77, 0x77, 0x77, 0x91, 0xB0}, "ADDI.W #0x7777,(0x91,A7,A0.L)"},

		// ADDI.L #imm,d8(An,Xn)
		{[]uint8{0x06, 0xB0, 0x12, 0x34, 0x56, 0x78, 0x12, 0x34}, "ADDI.L #0x12345678,(0x12,A0,D4.W)"},
		{[]uint8{0x06, 0xB4, 0xAB, 0xCD, 0xEF, 0x01, 0x56, 0x78}, "ADDI.L #0xABCDEF01,(0x56,A4,D7.W)"},
		{[]uint8{0x06, 0xB7, 0x77, 0x77, 0x77, 0x77, 0x91, 0x80}, "ADDI.L #0x77777777,(0x91,A7,D0.L)"},
		{[]uint8{0x06, 0xB0, 0x12, 0x34, 0x56, 0x78, 0x12, 0xB4}, "ADDI.L #0x12345678,(0x12,A0,A4.W)"},
		{[]uint8{0x06, 0xB4, 0xAB, 0xCD, 0xEF, 0x01, 0x56, 0xF8}, "ADDI.L #0xABCDEF01,(0x56,A4,A7.W)"},
		{[]uint8{0x06, 0xB7, 0x77, 0x77, 0x77, 0x77, 0x91, 0xB0}, "ADDI.L #0x77777777,(0x91,A7,A0.L)"},

		// ADDI.B #imm,xxx.W
		{[]uint8{0x06, 0x38, 0x00, 0x01, 0x12, 0x34}, "ADDI.B #0x01,(0x1234).W"},
		{[]uint8{0x06, 0x38, 0x00, 0xFF, 0x56, 0x78}, "ADDI.B #0xFF,(0x5678).W"},
		{[]uint8{0x06, 0x38, 0x00, 0x55, 0x90, 0xAB}, "ADDI.B #0x55,(0x90AB).W"},

		// ADDI.W #imm,xxx.W
		{[]uint8{0x06, 0x78, 0x12, 0x34, 0x12, 0x34}, "ADDI.W #0x1234,(0x1234).W"},
		{[]uint8{0x06, 0x78, 0xAB, 0xCD, 0x56, 0x78}, "ADDI.W #0xABCD,(0x5678).W"},
		{[]uint8{0x06, 0x78, 0x77, 0x77, 0x90, 0xAB}, "ADDI.W #0x7777,(0x90AB).W"},

		// ADDI.L #imm,xxx.W
		{[]uint8{0x06, 0xB8, 0x12, 0x34, 0x56, 0x78, 0x12, 0x34}, "ADDI.L #0x12345678,(0x1234).W"},
		{[]uint8{0x06, 0xB8, 0xAB, 0xCD, 0xEF, 0x01, 0x56, 0x78}, "ADDI.L #0xABCDEF01,(0x5678).W"},
		{[]uint8{0x06, 0xB8, 0x77, 0x77, 0x77, 0x77, 0x90, 0xAB}, "ADDI.L #0x77777777,(0x90AB).W"},

		// ADDI.B #imm,xxx.L
		{[]uint8{0x06, 0x39, 0x00, 0x01, 0x12, 0x34, 0x56, 0x78}, "ADDI.B #0x01,(0x12345678).L"},
		{[]uint8{0x06, 0x39, 0x00, 0xFF, 0x9A, 0xBC, 0xDE, 0xF0}, "ADDI.B #0xFF,(0x9ABCDEF0).L"},

		// ADDI.W #imm,xxx.L
		{[]uint8{0x06, 0x79, 0x12, 0x34, 0x12, 0x34, 0x56, 0x78}, "ADDI.W #0x1234,(0x12345678).L"},
		{[]uint8{0x06, 0x79, 0xAB, 0xCD, 0x9A, 0xBC, 0xDE, 0xF0}, "ADDI.W #0xABCD,(0x9ABCDEF0).L"},

		// ADDI.L #imm,xxx.L
		{[]uint8{0x06, 0xB9, 0x12, 0x34, 0x56, 0x78, 0x12, 0x34, 0x56, 0x78}, "ADDI.L #0x12345678,(0x12345678).L"},
		{[]uint8{0x06, 0xB9, 0xAB, 0xCD, 0xEF, 0x01, 0x9A, 0xBC, 0xDE, 0xF0}, "ADDI.L #0xABCDEF01,(0x9ABCDEF0).L"},
	}

	for _, tc := range testCases {
		t.Run(tc.expected, func(t *testing.T) {
			result := DisassembleInstruction(tc.bytes, 0)
			if result != tc.expected {
				t.Errorf("Expected %s, got %s", tc.expected, result)
			}
		})
	}
}
