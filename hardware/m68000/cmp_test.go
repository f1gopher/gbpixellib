package m68000

import "testing"

func TestDisassembleCMP(t *testing.T) {
	testCases := []testCase{
		// CMP - Compare
		// Format: 1011 rrr sss eeeeee
		// Where:
		// - rrr is the register number (D0-D7)
		// - sss is the size (001=byte, 011=word, 111=long)
		// - eeeeee defines the effective address (source operand)

		// CMP.B Dm,Dn (Compare byte register to register)
		{[]uint8{0xB0, 0x00}, "CMP.B D0,D0"},
		{[]uint8{0xB0, 0x01}, "CMP.B D1,D0"},
		{[]uint8{0xB0, 0x02}, "CMP.B D2,D0"},
		{[]uint8{0xB0, 0x03}, "CMP.B D3,D0"},
		{[]uint8{0xB0, 0x04}, "CMP.B D4,D0"},
		{[]uint8{0xB0, 0x05}, "CMP.B D5,D0"},
		{[]uint8{0xB0, 0x06}, "CMP.B D6,D0"},
		{[]uint8{0xB0, 0x07}, "CMP.B D7,D0"},

		{[]uint8{0xB2, 0x00}, "CMP.B D0,D1"},
		{[]uint8{0xB4, 0x00}, "CMP.B D0,D2"},
		{[]uint8{0xB6, 0x00}, "CMP.B D0,D3"},
		{[]uint8{0xB8, 0x00}, "CMP.B D0,D4"},
		{[]uint8{0xBA, 0x00}, "CMP.B D0,D5"},
		{[]uint8{0xBC, 0x00}, "CMP.B D0,D6"},
		{[]uint8{0xBE, 0x00}, "CMP.B D0,D7"},

		// Cross register tests for byte
		{[]uint8{0xB2, 0x03}, "CMP.B D3,D1"},
		{[]uint8{0xB4, 0x05}, "CMP.B D5,D2"},
		{[]uint8{0xB6, 0x06}, "CMP.B D6,D3"},
		{[]uint8{0xBC, 0x07}, "CMP.B D7,D6"},

		// CMP.W Dm,Dn (Compare word register to register)
		{[]uint8{0xB0, 0x40}, "CMP.W D0,D0"},
		{[]uint8{0xB0, 0x41}, "CMP.W D1,D0"},
		{[]uint8{0xB0, 0x42}, "CMP.W D2,D0"},
		{[]uint8{0xB0, 0x47}, "CMP.W D7,D0"},

		{[]uint8{0xB2, 0x40}, "CMP.W D0,D1"},
		{[]uint8{0xB4, 0x42}, "CMP.W D2,D2"},
		{[]uint8{0xBE, 0x47}, "CMP.W D7,D7"},

		// CMP.W An,Dn (Compare address register to data register)
		{[]uint8{0xB0, 0x48}, "CMP.W A0,D0"},
		{[]uint8{0xB0, 0x49}, "CMP.W A1,D0"},
		{[]uint8{0xB0, 0x4A}, "CMP.W A2,D0"},
		{[]uint8{0xB0, 0x4B}, "CMP.W A3,D0"},
		{[]uint8{0xB0, 0x4C}, "CMP.W A4,D0"},
		{[]uint8{0xB0, 0x4D}, "CMP.W A5,D0"},
		{[]uint8{0xB0, 0x4E}, "CMP.W A6,D0"},
		{[]uint8{0xB0, 0x4F}, "CMP.W A7,D0"},

		{[]uint8{0xB2, 0x48}, "CMP.W A0,D1"},
		{[]uint8{0xB4, 0x49}, "CMP.W A1,D2"},
		{[]uint8{0xBE, 0x4F}, "CMP.W A7,D7"},

		// CMP.L Dm,Dn (Compare long register to register)
		{[]uint8{0xB0, 0x80}, "CMP.L D0,D0"},
		{[]uint8{0xB0, 0x81}, "CMP.L D1,D0"},
		{[]uint8{0xB0, 0x87}, "CMP.L D7,D0"},

		{[]uint8{0xB2, 0x80}, "CMP.L D0,D1"},
		{[]uint8{0xBE, 0x87}, "CMP.L D7,D7"},

		// CMP.L An,Dn (Compare address register to data register)
		{[]uint8{0xB0, 0x88}, "CMP.L A0,D0"},
		{[]uint8{0xB0, 0x89}, "CMP.L A1,D0"},
		{[]uint8{0xB0, 0x8F}, "CMP.L A7,D0"},

		{[]uint8{0xB2, 0x88}, "CMP.L A0,D1"},
		{[]uint8{0xBE, 0x8F}, "CMP.L A7,D7"},

		// CMP.B (An),Dn (Compare memory to register)
		{[]uint8{0xB0, 0x10}, "CMP.B (A0),D0"},
		{[]uint8{0xB0, 0x11}, "CMP.B (A1),D0"},
		{[]uint8{0xB0, 0x17}, "CMP.B (A7),D0"},

		{[]uint8{0xB2, 0x10}, "CMP.B (A0),D1"},
		{[]uint8{0xBE, 0x17}, "CMP.B (A7),D7"},

		// CMP.W (An),Dn
		{[]uint8{0xB0, 0x50}, "CMP.W (A0),D0"},
		{[]uint8{0xB0, 0x51}, "CMP.W (A1),D0"},
		{[]uint8{0xB0, 0x57}, "CMP.W (A7),D0"},

		// CMP.L (An),Dn
		{[]uint8{0xB0, 0x90}, "CMP.L (A0),D0"},
		{[]uint8{0xB0, 0x91}, "CMP.L (A1),D0"},
		{[]uint8{0xB0, 0x97}, "CMP.L (A7),D0"},

		// CMP.B (An)+,Dn (Compare memory with postincrement to register)
		{[]uint8{0xB0, 0x18}, "CMP.B (A0)+,D0"},
		{[]uint8{0xB0, 0x19}, "CMP.B (A1)+,D0"},
		{[]uint8{0xB0, 0x1F}, "CMP.B (A7)+,D0"},

		// CMP.W (An)+,Dn
		{[]uint8{0xB0, 0x58}, "CMP.W (A0)+,D0"},
		{[]uint8{0xB0, 0x59}, "CMP.W (A1)+,D0"},
		{[]uint8{0xB0, 0x5F}, "CMP.W (A7)+,D0"},

		// CMP.L (An)+,Dn
		{[]uint8{0xB0, 0x98}, "CMP.L (A0)+,D0"},
		{[]uint8{0xB0, 0x99}, "CMP.L (A1)+,D0"},
		{[]uint8{0xB0, 0x9F}, "CMP.L (A7)+,D0"},

		// CMP.B -(An),Dn (Compare memory with predecrement to register)
		{[]uint8{0xB0, 0x20}, "CMP.B -(A0),D0"},
		{[]uint8{0xB0, 0x21}, "CMP.B -(A1),D0"},
		{[]uint8{0xB0, 0x27}, "CMP.B -(A7),D0"},

		// CMP.W -(An),Dn
		{[]uint8{0xB0, 0x60}, "CMP.W -(A0),D0"},
		{[]uint8{0xB0, 0x61}, "CMP.W -(A1),D0"},
		{[]uint8{0xB0, 0x67}, "CMP.W -(A7),D0"},

		// CMP.L -(An),Dn
		{[]uint8{0xB0, 0xA0}, "CMP.L -(A0),D0"},
		{[]uint8{0xB0, 0xA1}, "CMP.L -(A1),D0"},
		{[]uint8{0xB0, 0xA7}, "CMP.L -(A7),D0"},

		// CMP.B d16(An),Dn (Compare memory with displacement to register)
		{[]uint8{0xB0, 0x28, 0x12, 0x34}, "CMP.B (0x1234,A0),D0"},
		{[]uint8{0xB0, 0x29, 0x56, 0x78}, "CMP.B (0x5678,A1),D0"},
		{[]uint8{0xB0, 0x2F, 0x9A, 0xBC}, "CMP.B (0x9ABC,A7),D0"},

		// CMP.W d16(An),Dn
		{[]uint8{0xB0, 0x68, 0x12, 0x34}, "CMP.W (0x1234,A0),D0"},
		{[]uint8{0xB0, 0x69, 0x56, 0x78}, "CMP.W (0x5678,A1),D0"},
		{[]uint8{0xB0, 0x6F, 0x9A, 0xBC}, "CMP.W (0x9ABC,A7),D0"},

		// CMP.L d16(An),Dn
		{[]uint8{0xB0, 0xA8, 0x12, 0x34}, "CMP.L (0x1234,A0),D0"},
		{[]uint8{0xB0, 0xA9, 0x56, 0x78}, "CMP.L (0x5678,A1),D0"},
		{[]uint8{0xB0, 0xAF, 0x9A, 0xBC}, "CMP.L (0x9ABC,A7),D0"},

		// CMP.B d8(An,Xn),Dn (Compare memory with index to register)
		{[]uint8{0xB0, 0x30, 0x12, 0x34}, "CMP.B (0x12,A0,D4.W),D0"},
		{[]uint8{0xB0, 0x31, 0x56, 0x70}, "CMP.B (0x56,A1,D0.W),D0"},
		{[]uint8{0xB0, 0x37, 0x9A, 0xBC}, "CMP.B (0x9A,A7,D12.W),D0"},

		// CMP.B d8(An,Xn),Dn with address register index
		{[]uint8{0xB0, 0x30, 0x12, 0xB4}, "CMP.B (0x12,A0,A4.W),D0"},
		{[]uint8{0xB0, 0x31, 0x56, 0xF0}, "CMP.B (0x56,A1,A0.W),D0"},
		{[]uint8{0xB0, 0x37, 0x9A, 0xF7}, "CMP.B (0x9A,A7,A7.W),D0"},

		// CMP.W d8(An,Xn),Dn
		{[]uint8{0xB0, 0x70, 0x12, 0x34}, "CMP.W (0x12,A0,D4.W),D0"},
		{[]uint8{0xB0, 0x70, 0x12, 0xB4}, "CMP.W (0x12,A0,A4.W),D0"},

		// CMP.L d8(An,Xn),Dn
		{[]uint8{0xB0, 0xB0, 0x12, 0x34}, "CMP.L (0x12,A0,D4.W),D0"},
		{[]uint8{0xB0, 0xB0, 0x12, 0xB4}, "CMP.L (0x12,A0,A4.W),D0"},

		// CMP.B xxx.W,Dn (Compare absolute short address to register)
		{[]uint8{0xB0, 0x38, 0x12, 0x34}, "CMP.B (0x1234).W,D0"},
		{[]uint8{0xB0, 0x38, 0x56, 0x78}, "CMP.B (0x5678).W,D0"},
		{[]uint8{0xB2, 0x38, 0x9A, 0xBC}, "CMP.B (0x9ABC).W,D1"},

		// CMP.W xxx.W,Dn
		{[]uint8{0xB0, 0x78, 0x12, 0x34}, "CMP.W (0x1234).W,D0"},
		{[]uint8{0xB0, 0x78, 0x56, 0x78}, "CMP.W (0x5678).W,D0"},
		{[]uint8{0xB2, 0x78, 0x9A, 0xBC}, "CMP.W (0x9ABC).W,D1"},

		// CMP.L xxx.W,Dn
		{[]uint8{0xB0, 0xB8, 0x12, 0x34}, "CMP.L (0x1234).W,D0"},
		{[]uint8{0xB0, 0xB8, 0x56, 0x78}, "CMP.L (0x5678).W,D0"},
		{[]uint8{0xB2, 0xB8, 0x9A, 0xBC}, "CMP.L (0x9ABC).W,D1"},

		// CMP.B xxx.L,Dn (Compare absolute long address to register)
		{[]uint8{0xB0, 0x39, 0x12, 0x34, 0x56, 0x78}, "CMP.B (0x12345678).L,D0"},
		{[]uint8{0xB0, 0x39, 0x9A, 0xBC, 0xDE, 0xF0}, "CMP.B (0x9ABCDEF0).L,D0"},
		{[]uint8{0xB2, 0x39, 0x00, 0x00, 0x00, 0x01}, "CMP.B (0x00000001).L,D1"},

		// CMP.W xxx.L,Dn
		{[]uint8{0xB0, 0x79, 0x12, 0x34, 0x56, 0x78}, "CMP.W (0x12345678).L,D0"},
		{[]uint8{0xB0, 0x79, 0x9A, 0xBC, 0xDE, 0xF0}, "CMP.W (0x9ABCDEF0).L,D0"},
		{[]uint8{0xB2, 0x79, 0x00, 0x00, 0x00, 0x01}, "CMP.W (0x00000001).L,D1"},

		// CMP.L xxx.L,Dn
		{[]uint8{0xB0, 0xB9, 0x12, 0x34, 0x56, 0x78}, "CMP.L (0x12345678).L,D0"},
		{[]uint8{0xB0, 0xB9, 0x9A, 0xBC, 0xDE, 0xF0}, "CMP.L (0x9ABCDEF0).L,D0"},
		{[]uint8{0xB2, 0xB9, 0x00, 0x00, 0x00, 0x01}, "CMP.L (0x00000001).L,D1"},

		// CMP.B #imm,Dn (Compare immediate to register)
		{[]uint8{0xB0, 0x3C, 0x00, 0x12}, "CMP.B #0x12,D0"},
		{[]uint8{0xB0, 0x3C, 0x00, 0x34}, "CMP.B #0x34,D0"},
		{[]uint8{0xB2, 0x3C, 0x00, 0x56}, "CMP.B #0x56,D1"},
		{[]uint8{0xB2, 0x3C, 0x00, 0x78}, "CMP.B #0x78,D1"},
		{[]uint8{0xB4, 0x3C, 0x00, 0x9A}, "CMP.B #0x9A,D2"},
		{[]uint8{0xB4, 0x3C, 0x00, 0xBC}, "CMP.B #0xBC,D2"},
		{[]uint8{0xBE, 0x3C, 0x00, 0xDE}, "CMP.B #0xDE,D7"},
		{[]uint8{0xBE, 0x3C, 0x00, 0xF0}, "CMP.B #0xF0,D7"},

		// CMP.W #imm,Dn
		{[]uint8{0xB0, 0x7C, 0x12, 0x34}, "CMP.W #0x1234,D0"},
		{[]uint8{0xB0, 0x7C, 0x56, 0x78}, "CMP.W #0x5678,D0"},
		{[]uint8{0xB2, 0x7C, 0x9A, 0xBC}, "CMP.W #0x9ABC,D1"},
		{[]uint8{0xB2, 0x7C, 0xDE, 0xF0}, "CMP.W #0xDEF0,D1"},
		{[]uint8{0xBE, 0x7C, 0x00, 0x00}, "CMP.W #0x0000,D7"},
		{[]uint8{0xBE, 0x7C, 0xFF, 0xFF}, "CMP.W #0xFFFF,D7"},

		// CMP.L #imm,Dn
		{[]uint8{0xB0, 0xBC, 0x12, 0x34, 0x56, 0x78}, "CMP.L #0x12345678,D0"},
		{[]uint8{0xB0, 0xBC, 0x9A, 0xBC, 0xDE, 0xF0}, "CMP.L #0x9ABCDEF0,D0"},
		{[]uint8{0xB2, 0xBC, 0x00, 0x00, 0x00, 0x00}, "CMP.L #0x00000000,D1"},
		{[]uint8{0xB2, 0xBC, 0xFF, 0xFF, 0xFF, 0xFF}, "CMP.L #0xFFFFFFFF,D1"},
		{[]uint8{0xBE, 0xBC, 0x80, 0x00, 0x00, 0x00}, "CMP.L #0x80000000,D7"},
		{[]uint8{0xBE, 0xBC, 0x7F, 0xFF, 0xFF, 0xFF}, "CMP.L #0x7FFFFFFF,D7"},

		// CMP.B d16(PC),Dn (Compare PC-relative to register)
		{[]uint8{0xB0, 0x3A, 0x12, 0x34}, "CMP.B (0x1234,PC),D0"},
		{[]uint8{0xB0, 0x3A, 0x56, 0x78}, "CMP.B (0x5678,PC),D0"},
		{[]uint8{0xB2, 0x3A, 0x9A, 0xBC}, "CMP.B (0x9ABC,PC),D1"},

		// CMP.W d16(PC),Dn
		{[]uint8{0xB0, 0x7A, 0x12, 0x34}, "CMP.W (0x1234,PC),D0"},
		{[]uint8{0xB0, 0x7A, 0x56, 0x78}, "CMP.W (0x5678,PC),D0"},
		{[]uint8{0xB2, 0x7A, 0x9A, 0xBC}, "CMP.W (0x9ABC,PC),D1"},

		// CMP.L d16(PC),Dn
		{[]uint8{0xB0, 0xBA, 0x12, 0x34}, "CMP.L (0x1234,PC),D0"},
		{[]uint8{0xB0, 0xBA, 0x56, 0x78}, "CMP.L (0x5678,PC),D0"},
		{[]uint8{0xB2, 0xBA, 0x9A, 0xBC}, "CMP.L (0x9ABC,PC),D1"},

		// CMP.B d8(PC,Xn),Dn (Compare PC-relative with index to register)
		{[]uint8{0xB0, 0x3B, 0x12, 0x34}, "CMP.B (0x12,PC,D4.W),D0"},
		{[]uint8{0xB0, 0x3B, 0x56, 0x70}, "CMP.B (0x56,PC,D0.W),D0"},
		{[]uint8{0xB2, 0x3B, 0x9A, 0xBC}, "CMP.B (0x9A,PC,D12.W),D1"},

		// CMP.B d8(PC,Xn),Dn with address register index
		{[]uint8{0xB0, 0x3B, 0x12, 0xB4}, "CMP.B (0x12,PC,A4.W),D0"},
		{[]uint8{0xB0, 0x3B, 0x56, 0xF0}, "CMP.B (0x56,PC,A0.W),D0"},
		{[]uint8{0xB2, 0x3B, 0x9A, 0xF7}, "CMP.B (0x9A,PC,A7.W),D1"},

		// CMP.W d8(PC,Xn),Dn
		{[]uint8{0xB0, 0x7B, 0x12, 0x34}, "CMP.W (0x12,PC,D4.W),D0"},
		{[]uint8{0xB0, 0x7B, 0x12, 0xB4}, "CMP.W (0x12,PC,A4.W),D0"},

		// CMP.L d8(PC,Xn),Dn
		{[]uint8{0xB0, 0xBB, 0x12, 0x34}, "CMP.L (0x12,PC,D4.W),D0"},
		{[]uint8{0xB0, 0xBB, 0x12, 0xB4}, "CMP.L (0x12,PC,A4.W),D0"},
	}

	runTests(t, testCases)
}
