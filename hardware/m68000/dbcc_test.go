package m68000

import "testing"

func TestDisassembleDBcc(t *testing.T) {
	testCases := []testCaseWithAddress{
		// DBcc - Decrement and Branch on Condition
		// Format: 0101 CCCC 11001 rrr followed by displacement word
		// Where:
		// - CCCC is the condition code (0000=T, 0001=F, etc.)
		// - rrr is the data register number (D0-D7)
		// - Displacement word is the PC-relative branch offset

		// The DBcc instruction:
		// 1. Tests the condition
		// 2. If the condition is true, continues to the next instruction
		// 3. If the condition is false, decrements the register
		// 4. If the register is not -1, branches to the target address
		// 5. If the register is -1, continues to the next instruction

		// DBT - Decrement and Branch on True (always true, so never branches)
		{[]uint8{0x50, 0xC8, 0x00, 0x10}, "DBT D0,$0012", 0x0000},
		{[]uint8{0x51, 0xC8, 0x00, 0x10}, "DBT D1,$0012", 0x0000},
		{[]uint8{0x52, 0xC8, 0x00, 0x10}, "DBT D2,$0012", 0x0000},
		{[]uint8{0x53, 0xC8, 0x00, 0x10}, "DBT D3,$0012", 0x0000},
		{[]uint8{0x54, 0xC8, 0x00, 0x10}, "DBT D4,$0012", 0x0000},
		{[]uint8{0x55, 0xC8, 0x00, 0x10}, "DBT D5,$0012", 0x0000},
		{[]uint8{0x56, 0xC8, 0x00, 0x10}, "DBT D6,$0012", 0x0000},
		{[]uint8{0x57, 0xC8, 0x00, 0x10}, "DBT D7,$0012", 0x0000},

		// DBF/DBRA - Decrement and Branch on False (always branches until counter becomes -1)
		{[]uint8{0x50, 0xC9, 0x00, 0x10}, "DBF D0,$0012", 0x0000},
		{[]uint8{0x51, 0xC9, 0x00, 0x10}, "DBF D1,$0012", 0x0000},
		{[]uint8{0x52, 0xC9, 0x00, 0x10}, "DBF D2,$0012", 0x0000},
		{[]uint8{0x53, 0xC9, 0x00, 0x10}, "DBF D3,$0012", 0x0000},
		{[]uint8{0x54, 0xC9, 0x00, 0x10}, "DBF D4,$0012", 0x0000},
		{[]uint8{0x55, 0xC9, 0x00, 0x10}, "DBF D5,$0012", 0x0000},
		{[]uint8{0x56, 0xC9, 0x00, 0x10}, "DBF D6,$0012", 0x0000},
		{[]uint8{0x57, 0xC9, 0x00, 0x10}, "DBF D7,$0012", 0x0000},

		// DBRA is a synonym for DBF (more descriptive for loop counting)
		{[]uint8{0x51, 0xC9, 0x00, 0x20}, "DBF D1,$0022", 0x0000},

		// DBHI - Decrement and Branch on Higher
		{[]uint8{0x50, 0xCA, 0x00, 0x10}, "DBHI D0,$0012", 0x0000},
		{[]uint8{0x52, 0xCA, 0x00, 0x10}, "DBHI D2,$0012", 0x0000},
		{[]uint8{0x57, 0xCA, 0x00, 0x10}, "DBHI D7,$0012", 0x0000},

		// DBLS - Decrement and Branch on Lower or Same
		{[]uint8{0x50, 0xCB, 0x00, 0x10}, "DBLS D0,$0012", 0x0000},
		{[]uint8{0x52, 0xCB, 0x00, 0x10}, "DBLS D2,$0012", 0x0000},
		{[]uint8{0x57, 0xCB, 0x00, 0x10}, "DBLS D7,$0012", 0x0000},

		// DBCC/DBHS - Decrement and Branch on Carry Clear/Higher or Same
		{[]uint8{0x50, 0xCC, 0x00, 0x10}, "DBCC D0,$0012", 0x0000},
		{[]uint8{0x52, 0xCC, 0x00, 0x10}, "DBCC D2,$0012", 0x0000},
		{[]uint8{0x57, 0xCC, 0x00, 0x10}, "DBCC D7,$0012", 0x0000},

		// DBCS/DBLO - Decrement and Branch on Carry Set/Lower
		{[]uint8{0x50, 0xCD, 0x00, 0x10}, "DBCS D0,$0012", 0x0000},
		{[]uint8{0x52, 0xCD, 0x00, 0x10}, "DBCS D2,$0012", 0x0000},
		{[]uint8{0x57, 0xCD, 0x00, 0x10}, "DBCS D7,$0012", 0x0000},

		// DBNE - Decrement and Branch on Not Equal
		{[]uint8{0x50, 0xCE, 0x00, 0x10}, "DBNE D0,$0012", 0x0000},
		{[]uint8{0x52, 0xCE, 0x00, 0x10}, "DBNE D2,$0012", 0x0000},
		{[]uint8{0x57, 0xCE, 0x00, 0x10}, "DBNE D7,$0012", 0x0000},

		// DBEQ - Decrement and Branch on Equal
		{[]uint8{0x50, 0xCF, 0x00, 0x10}, "DBEQ D0,$0012", 0x0000},
		{[]uint8{0x52, 0xCF, 0x00, 0x10}, "DBEQ D2,$0012", 0x0000},
		{[]uint8{0x57, 0xCF, 0x00, 0x10}, "DBEQ D7,$0012", 0x0000},

		// DBVC - Decrement and Branch on Overflow Clear
		{[]uint8{0x50, 0xD0, 0x00, 0x10}, "DBVC D0,$0012", 0x0000},
		{[]uint8{0x52, 0xD0, 0x00, 0x10}, "DBVC D2,$0012", 0x0000},
		{[]uint8{0x57, 0xD0, 0x00, 0x10}, "DBVC D7,$0012", 0x0000},

		// DBVS - Decrement and Branch on Overflow Set
		{[]uint8{0x50, 0xD1, 0x00, 0x10}, "DBVS D0,$0012", 0x0000},
		{[]uint8{0x52, 0xD1, 0x00, 0x10}, "DBVS D2,$0012", 0x0000},
		{[]uint8{0x57, 0xD1, 0x00, 0x10}, "DBVS D7,$0012", 0x0000},

		// DBPL - Decrement and Branch on Plus
		{[]uint8{0x50, 0xD2, 0x00, 0x10}, "DBPL D0,$0012", 0x0000},
		{[]uint8{0x52, 0xD2, 0x00, 0x10}, "DBPL D2,$0012", 0x0000},
		{[]uint8{0x57, 0xD2, 0x00, 0x10}, "DBPL D7,$0012", 0x0000},

		// DBMI - Decrement and Branch on Minus
		{[]uint8{0x50, 0xD3, 0x00, 0x10}, "DBMI D0,$0012", 0x0000},
		{[]uint8{0x52, 0xD3, 0x00, 0x10}, "DBMI D2,$0012", 0x0000},
		{[]uint8{0x57, 0xD3, 0x00, 0x10}, "DBMI D7,$0012", 0x0000},

		// DBGE - Decrement and Branch on Greater or Equal
		{[]uint8{0x50, 0xD4, 0x00, 0x10}, "DBGE D0,$0012", 0x0000},
		{[]uint8{0x52, 0xD4, 0x00, 0x10}, "DBGE D2,$0012", 0x0000},
		{[]uint8{0x57, 0xD4, 0x00, 0x10}, "DBGE D7,$0012", 0x0000},

		// DBLT - Decrement and Branch on Less Than
		{[]uint8{0x50, 0xD5, 0x00, 0x10}, "DBLT D0,$0012", 0x0000},
		{[]uint8{0x52, 0xD5, 0x00, 0x10}, "DBLT D2,$0012", 0x0000},
		{[]uint8{0x57, 0xD5, 0x00, 0x10}, "DBLT D7,$0012", 0x0000},

		// DBGT - Decrement and Branch on Greater Than
		{[]uint8{0x50, 0xD6, 0x00, 0x10}, "DBGT D0,$0012", 0x0000},
		{[]uint8{0x52, 0xD6, 0x00, 0x10}, "DBGT D2,$0012", 0x0000},
		{[]uint8{0x57, 0xD6, 0x00, 0x10}, "DBGT D7,$0012", 0x0000},

		// DBLE - Decrement and Branch on Less or Equal
		{[]uint8{0x50, 0xD7, 0x00, 0x10}, "DBLE D0,$0012", 0x0000},
		{[]uint8{0x52, 0xD7, 0x00, 0x10}, "DBLE D2,$0012", 0x0000},
		{[]uint8{0x57, 0xD7, 0x00, 0x10}, "DBLE D7,$0012", 0x0000},

		// Testing different displacement values
		{[]uint8{0x51, 0xC9, 0xFF, 0xF0}, "DBF D1,$FFF2", 0x0000}, // Branch backward
		{[]uint8{0x51, 0xC9, 0x7F, 0xFF}, "DBF D1,$8001", 0x0000}, // Maximum forward branch
		{[]uint8{0x51, 0xC9, 0x80, 0x00}, "DBF D1,$8002", 0x0000}, // Maximum backward branch
		{[]uint8{0x51, 0xC9, 0x00, 0x00}, "DBF D1,$0002", 0x0000}, // Branch to PC+2

		// Testing with different PC values
		{[]uint8{0x51, 0xC9, 0x00, 0x10}, "DBF D1,$1012", 0x1000},  // At address 0x1000
		{[]uint8{0x51, 0xC9, 0xFF, 0xF0}, "DBF D1,$0FF2", 0x1000},  // Branch backward from 0x1000
		{[]uint8{0x54, 0xD6, 0x00, 0x20}, "DBGT D4,$2022", 0x2000}, // At address 0x2000
		{[]uint8{0x54, 0xD6, 0xFF, 0xE0}, "DBGT D4,$1FE2", 0x2000}, // Branch backward from 0x2000

		// Special cases: Loop back to the same instruction (useful for spinlocks)
		{[]uint8{0x50, 0xC9, 0xFF, 0xFE}, "DBF D0,$0000", 0x0000}, // Branch to self
		{[]uint8{0x50, 0xC9, 0xFF, 0xFE}, "DBF D0,$1000", 0x1000}, // Branch to self from 0x1000
	}

	runAddressTests(t, testCases)
}
